#!/usr/bin/env node
// Static site build: node apps/website/build.mjs [--out <dir>]
// Assembles src/layout.html, src/styles, src/scripts and sections/<id>/ into a
// self-contained directory (default apps/website/dist). No network, no
// dependencies beyond Node. Output is byte-for-byte deterministic.
import { cp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { isInside, listFiles, sha256 } from './lib/files.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '..', '..')

/** Page order. Each id maps to sections/<id>/<id>.html and <id>.css. */
export const SECTIONS = ['hero', 'features', 'how', 'install', 'faq']
export const DEFAULT_OUT = path.join(here, 'dist')
export const MARKER = '.openfarm-website-build'

// Prettier would mangle a {{placeholder}} inside <script>, so use a JS comment.
const THEME_INIT_MARKER = '/*theme-init*/'
const REPO_URL = 'https://github.com/bloodf/Open3DFarmManager'
const SCREENSHOTS_DIR = path.join(repoRoot, 'docs', 'images')
const SCREENSHOTS = ['app-home.png', 'app-login.png', 'app-pairing.png']
const PAGE = {
  title: 'Open3DFarmManager — sua farm de impressão, em um só lugar',
  description:
    'Projeto open source em desenvolvimento para reunir impressoras Klipper/Moonraker, materiais do Spoolman e acesso pelo navegador, com um Connector na sua rede local.',
}

const read = (...parts) => readFile(path.join(here, ...parts), 'utf8')

function fill(template, values, label) {
  const result = template.replace(/\{\{([\w-]+)\}\}/g, (match, key) => {
    if (!(key in values))
      throw new Error(`${label}: unknown placeholder ${match}`)
    return values[key]
  })
  return result
}

function escapeAttr(text) {
  return text
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
}

/** Reject anything that would make the page request another origin. */
function assertSelfContained(label, source) {
  const remote = [
    /<(?:img|script|source|iframe|video|audio|link)\b[^>]*\b(?:src|href|srcset|poster)\s*=\s*["']?(?:https?:)?\/\//i,
    /url\(\s*["']?(?:https?:)?\/\//i,
    /@import/i,
  ]
  for (const pattern of remote) {
    if (pattern.test(source)) {
      throw new Error(
        `${label}: external runtime request is not allowed (${pattern})`,
      )
    }
  }
}

async function loadSection(id) {
  const label = `sections/${id}`
  const html = (await read('sections', id, `${id}.html`)).trim()
  const css = (await read('sections', id, `${id}.css`)).trim()
  const match = html.match(/^<section\b[^>]*\bid="([^"]+)"[^>]*>/)
  if (!match)
    throw new Error(`${label}: fragment must start with <section id="...">`)
  if (!/aria-labelledby="[^"]+"/.test(match[0])) {
    throw new Error(`${label}: <section> needs aria-labelledby`)
  }
  if (/<script\b/i.test(html))
    throw new Error(`${label}: scripts are not allowed in fragments`)
  assertSelfContained(`${label}/${id}.html`, html)
  assertSelfContained(`${label}/${id}.css`, css)
  const nav = match[0].match(/\bdata-nav="([^"]+)"/)
  return { id, anchor: match[1], navLabel: nav?.[1] ?? null, html, css }
}

async function prepareOutDir(outDir) {
  const exists = await stat(outDir).then(
    () => true,
    () => false,
  )
  if (exists) {
    const owned = await stat(path.join(outDir, MARKER)).then(
      () => true,
      () => false,
    )
    if (!owned) {
      throw new Error(
        `Refusing to clear ${outDir}: it has no ${MARKER} marker.`,
      )
    }
    await rm(outDir, { recursive: true, force: true })
  }
  await mkdir(path.join(outDir, 'assets', 'screenshots'), { recursive: true })
  await writeFile(
    path.join(outDir, MARKER),
    'Generated by apps/website/build.mjs\n',
  )
}

export async function build({ outDir = DEFAULT_OUT } = {}) {
  const out = path.resolve(outDir)
  if (isInside(out, here)) {
    throw new Error('Output directory must not contain the website sources.')
  }
  const sections = await Promise.all(SECTIONS.map(loadSection))
  const anchors = sections.map((section) => section.anchor)
  if (new Set(anchors).size !== anchors.length) {
    throw new Error(`Duplicate section ids: ${anchors.join(', ')}`)
  }

  const values = { repo: REPO_URL }
  const nav = sections
    .filter((section) => section.navLabel)
    .map(
      (section) =>
        `<li><a href="#${section.anchor}">${escapeAttr(section.navLabel)}</a></li>`,
    )
    .join('\n')
  const body = sections
    .map((section) => fill(section.html, values, section.id))
    .join('\n')

  const layout = await read('src', 'layout.html')
  const page = fill(
    layout,
    {
      ...values,
      title: escapeAttr(PAGE.title),
      description: escapeAttr(PAGE.description),
      nav,
      sections: body,
    },
    'layout.html',
  )

  if (!layout.includes(THEME_INIT_MARKER)) {
    throw new Error(`layout.html: missing ${THEME_INIT_MARKER}`)
  }
  const themeInit = (await read('src', 'scripts', 'theme-init.js')).trim()
  const finalPage = page.replace(THEME_INIT_MARKER, () => themeInit)
  if (finalPage.includes('{{'))
    throw new Error('layout.html: unresolved placeholder')

  const shellCss = await Promise.all(
    ['tokens', 'base', 'shell'].map(async (name) => {
      const css = await read('src', 'styles', `${name}.css`)
      assertSelfContained(`src/styles/${name}.css`, css)
      return `/* src/styles/${name}.css */\n${css.trim()}`
    }),
  )
  const sectionCss = sections.map(
    (section) =>
      `/* sections/${section.id}/${section.id}.css */\n${section.css}`,
  )

  await prepareOutDir(out)
  await writeFile(path.join(out, 'index.html'), finalPage)
  await writeFile(
    path.join(out, 'assets', 'site.css'),
    `${[...shellCss, ...sectionCss].join('\n\n')}\n`,
  )
  await writeFile(
    path.join(out, 'assets', 'site.js'),
    await read('src', 'scripts', 'site.js'),
  )
  await cp(path.join(here, 'src', 'assets'), path.join(out, 'assets'), {
    recursive: true,
  })
  for (const name of SCREENSHOTS) {
    await cp(
      path.join(SCREENSHOTS_DIR, name),
      path.join(out, 'assets', 'screenshots', name),
    )
  }

  const files = (await listFiles(out)).filter((file) => file !== MARKER)
  const manifest = {}
  for (const file of files) manifest[file] = await sha256(path.join(out, file))
  await writeFile(
    path.join(out, MARKER),
    `${JSON.stringify(manifest, null, 2)}\n`,
  )
  return { outDir: out, files, manifest }
}

function parseArgs(argv) {
  const index = argv.indexOf('--out')
  if (index === -1) return {}
  const value = argv[index + 1]
  if (!value) throw new Error('--out needs a directory')
  return { outDir: value }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  try {
    const { outDir, files } = await build(parseArgs(process.argv.slice(2)))
    process.stdout.write(
      `Built ${files.length} files in ${path.relative(process.cwd(), outDir) || '.'}\n`,
    )
    process.stdout.write(`Open ${path.join(outDir, 'index.html')}\n`)
  } catch (error) {
    process.stderr.write(`Build failed: ${error.message}\n`)
    process.exitCode = 1
  }
}
