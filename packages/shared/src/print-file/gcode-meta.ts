import { PrintFileMetadata } from './metadata.ts'

const HEADER_WINDOW = 4 * 1024 * 1024
const TAIL_WINDOW = 256 * 1024
const MAX_THUMBNAIL = 256 * 1024

/** A random-access source. read must return at most length bytes from offset. */
export interface GcodeSource {
  size: number
  read(offset: number, length: number): Promise<Uint8Array>
}

/** Reads at most 4.25 MiB, independently of the size of the G-code file. */
export async function parseGcodeMetadata(
  source: GcodeSource,
): Promise<PrintFileMetadata> {
  if (!Number.isSafeInteger(source.size) || source.size < 0) return {}
  const firstLength = Math.min(source.size, HEADER_WINDOW)
  const tailOffset = Math.max(firstLength, source.size - TAIL_WINDOW)
  const decoder = new TextDecoder()
  const first = await source.read(0, firstLength)
  const tail =
    tailOffset < source.size
      ? await source.read(tailOffset, source.size - tailOffset)
      : new Uint8Array()
  const text =
    decoder.decode(first.subarray(0, firstLength)) +
    '\n' +
    decoder.decode(tail.subarray(0, source.size - tailOffset))
  return parseGcodeMetadataText(text)
}

/** Parse bounded header and footer text without interpreting G-code commands. */
export function parseGcodeMetadataText(text: string): PrintFileMetadata {
  const result: PrintFileMetadata = {}
  const values = new Map<string, string>()
  text = text.slice(0, HEADER_WINDOW + TAIL_WINDOW + 1)
  const lines = text.split(/\r?\n/)
  for (const line of lines) {
    const match = /^\s*;\s*([^=:\r\n]+?)\s*[=:]\s*(.*?)\s*$/.exec(line)
    if (match?.[1] && match[2])
      values.set(match[1].trim().toLowerCase(), match[2].trim())
  }
  const get = (...keys: string[]) =>
    keys.map((key) => values.get(key)).find(Boolean)
  const slicer =
    /(?:generated by|sliced (?:at|by))\s+(PrusaSlicer|SuperSlicer|OrcaSlicer|BambuStudio|Bambu Studio|Creality Print|Anycubic Slicer Next|Cura(?:_SteamEngine)?)\s*([^\s;]*)/i.exec(
      text,
    )
  if (slicer?.[1]) {
    result.slicer = slicer[1]
      .replace('BambuStudio', 'Bambu Studio')
      .replace('Cura_SteamEngine', 'Cura')
    if (slicer[2] && /^v?\d/.test(slicer[2]))
      result.slicerVersion = slicer[2].replace(/^v/, '')
  } else if (get('flavor')) result.slicer = 'Cura'
  const assignString = (
    key: 'printerModel' | 'printerProfile' | 'printProfile' | 'filamentProfile',
    ...aliases: string[]
  ) => {
    const value = get(...aliases)
    if (value) result[key] = value
  }
  assignString('printerModel', 'printer_model', 'printer model', 'machine_name')
  assignString(
    'printerProfile',
    'printer_settings_id',
    'printer_preset',
    'printer profile',
  )
  assignString(
    'printProfile',
    'print_settings_id',
    'process_settings_id',
    'print profile',
  )
  assignString('filamentProfile', 'filament_settings_id', 'filament profile')
  const number = (value: string | undefined) => {
    if (!value || !/^\s*\d+(?:\.\d+)?/.test(value)) return undefined
    const n = Number.parseFloat(value)
    return Number.isFinite(n) ? n : undefined
  }
  const layer = number(get('layer_height', 'layer height'))
  if (layer && layer > 0) result.layerHeight = layer
  const firstLayer = number(
    get(
      'first_layer_height',
      'initial_layer_print_height',
      'first layer height',
    ),
  )
  if (firstLayer && firstLayer > 0 && !get('first_layer_height')?.includes('%'))
    result.firstLayerHeight = firstLayer
  const count = number(get('object_count', 'object count', 'total objects'))
  if (count !== undefined && Number.isInteger(count)) result.objectCount = count
  const layers = number(
    get('total_layer_count', 'total layers', 'layer_count', 'layer count'),
  )
  if (layers !== undefined && Number.isInteger(layers))
    result.totalLayers = layers
  const time = get(
    'time',
    'estimated printing time (normal mode)',
    'estimated printing time',
    'estimated_time',
  )
  if (time) {
    const plain = /^\d+(?:\.\d+)?$/.test(time) ? Number(time) : undefined
    let seconds = 0
    for (const part of time.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/gi))
      seconds +=
        Number(part[1]) *
        ({ d: 86400, h: 3600, m: 60, s: 1 }[part[2]!.toLowerCase()] ?? 0)
    if (plain !== undefined || seconds > 0)
      result.estimatedTimeSeconds = plain ?? seconds
  }
  const bed = get('bed_shape', 'printable_area', 'bed_size')
  if (bed) {
    const nums = bed.match(/\d+(?:\.\d+)?/g)?.map(Number)
    if (nums && nums.length >= 2 && nums.every(Number.isFinite))
      result.bedSize = nums
  }
  const lists = [
    get('nozzle_diameter', 'machine_nozzle_size'),
    get('filament_type', 'material_type'),
    get(
      'filament_colour',
      'filament_color',
      'material_colour',
      'material_color',
    ),
    get('filament used [g]', 'filament_used_g', 'filament weight'),
  ].map((value) => value?.split(/[;,]/).map((item) => item.trim()) ?? [])
  const tools: NonNullable<PrintFileMetadata['tools']> = []
  for (
    let i = 0;
    i < Math.min(64, Math.max(...lists.map((list) => list.length)));
    i++
  ) {
    const tool: NonNullable<PrintFileMetadata['tools']>[number] = {}
    const nozzle = number(lists[0]?.[i])
    if (nozzle && nozzle > 0) tool.nozzleDiameter = nozzle
    const type = lists[1]?.[i]
    if (type) tool.filamentType = type
    const colour = lists[2]?.[i]
    if (colour) tool.filamentColour = colour
    const grams = number(lists[3]?.[i])
    if (grams !== undefined) tool.filamentGrams = grams
    tools.push(tool)
  }
  if (tools.length) result.tools = tools
  let largest = 0
  for (const block of text.matchAll(
    /;\s*thumbnail(?:_PNG|_JPG)?\s+begin\s+\d+x\d+\s+\d+\s*\r?\n([\s\S]*?);\s*thumbnail(?:_PNG|_JPG)?\s+end/gi,
  )) {
    const data = (block[1] ?? '').replace(/^\s*;\s?/gm, '').replace(/\s/g, '')
    if (
      data.length > Math.ceil(MAX_THUMBNAIL / 3) * 4 ||
      !/^[A-Za-z0-9+/]*={0,2}$/.test(data)
    )
      continue
    try {
      const raw = atob(data)
      if (raw.length > MAX_THUMBNAIL || raw.length <= largest) continue
      const png = raw.startsWith('\x89PNG\r\n\x1a\n')
      const jpg = raw.startsWith('\xff\xd8\xff')
      if (png || jpg) {
        largest = raw.length
        result.thumbnail = { mimeType: png ? 'image/png' : 'image/jpeg', data }
      }
    } catch {
      /* Ignore incomplete base64 blocks. */
    }
  }
  return PrintFileMetadata.parse(result)
}
