const NOT_SENT = 'O comando não foi enviado ao Connector'
const OUTCOME =
  /Impressão iniciada|não foi iniciada|Não foi possível confirmar|não foi enviado/

/** The printer's stored state, when the server observed it just now. */
async function storedState(farm: FarmManager, page: Page, printerKey: string) {
  const response = await page.request.get(
    `${farm.origin}/api/farms/${farm.farmId}/printer-states`,
  )
  if (!response.ok()) return undefined
  const { states } = (await response.json()) as {
    states: Array<{ printerKey: string; state: string; observedAt: number }>
  }
  return states.find(
    (item) =>
      item.printerKey === printerKey && Date.now() - item.observedAt < 60_000,
  )?.state
}

/**
 * Opens the replay dialog, picks the printer and confirms. Every command opens
 * its own signed session, so the Connector's inbox must be listening first; a
 * session that closed before it was ready sends nothing and the dialog
 * reports a plain "not sent" (no reason). That outcome is repeated from a
 * fresh dialog; any other outcome, a refusal included, is returned as shown.
 */
async function replayFromDialog(
  farm: FarmManager,
  page: Page,
  open: () => Promise<void>,
  printerKey: string,
): Promise<string> {
  const dialog = page.getByRole('dialog', { name: 'Imprimir de novo' })
  for (let attempt = 1; ; attempt++) {
    await open()
    await expect(dialog.getByLabel(printerKey)).toBeEnabled({ timeout: 90_000 })
    await dialog.getByLabel(printerKey).check()
    await dialog.getByLabel(/mesa está limpa/).check()
    await expect
      .poll(() => farm.commandInboxReady(printerKey), { timeout: 90_000 })
      .toBe(true)
    // The server signs a command capability only from fresh stored controls.
    await expect
      .poll(() => storedState(farm, page, printerKey), { timeout: 90_000 })
      .toBe('idle')
    await dialog
      .getByRole('button', { name: 'Imprimir de novo', exact: true })
      .click()
    await expect(dialog.getByText(OUTCOME).first()).toBeVisible({
      timeout: 120_000,
    })
    const text = await dialog.innerText()
    if (!text.includes(NOT_SENT)) return text
    if (attempt >= 2) throw new Error('A sessão de comando falhou 2 vezes')
    await dialog.getByRole('button', { name: /^(Cancelar|Fechar)$/ }).click()
    await expect(dialog).toBeHidden()
    // Gives the Connector time to listen for a new session.
    await page.waitForTimeout(3000)
  }
}

/**
 * The Connector checks a library file against the profile the printer itself
 * reported, and a Moonraker machine block rides on the next status snapshot
 * after the Connector reads it. A real printer's temperatures keep drifting,
 * so snapshots keep coming; the static mocks drift on a timer instead.
 * Returns the function that stops it.
 */
function drift(mocks: readonly MoonrakerSimulator[]) {
  let step = 0
  const timer = setInterval(() => {
    step += 1
    for (const mock of mocks) mock.update({ fan: (step % 9) / 10 })
  }, 500)
  return () => clearInterval(timer)
}

const sha256 = (text: string) => createHash('sha256').update(text).digest('hex')

let stopDrift = () => {}
test.afterEach(() => stopDrift())

const GCODE = [
  '; generated by PrusaSlicer 2.7.1',
  '; estimated printing time (normal mode) = 10m 0s',
  'G28',
  'G1 X10 Y10 F3000',
  '',
].join('\n')
const GCODE_CONNECTOR = GCODE.replace('2.7.1', '2.7.2').replace('10m', '12m')

/** Klipper settings the mock reports so the Connector knows its nozzle. */
const MOCK = {
  initial: { state: 'standby', progress: 0, filename: '' },
  mock: {
    configfileSettings: { extruder: { nozzle_diameter: 0.4, max_temp: 300 } },
  },
} as const

async function blobs(directory: string) {
  try {
    return (await readdir(directory)).filter((name) =>
      /^[0-9a-f]{64}$/.test(name),
    )
  } catch {
    return []
  }
}

test('envia e imprime arquivos da biblioteca com armazenamento no servidor e no Connector', async ({
  bootFarm,
}) => {
  const farm = await bootFarm({
    printers: [
      { family: 'moonraker', printerKey: 'moonraker-a' },
      {
        family: 'moonraker',
        printerKey: 'moonraker-b',
        moonraker: MOCK,
        control: true,
      },
    ],
    connectAll: true,
    history: true,
    signedControl: true,
    moonraker: MOCK,
  })
  const page = farm.owner
  const [a, b] = farm.printers.map((p) => p.mock as MoonrakerSimulator)
  stopDrift = drift([a!, b!])
  const printed = (mock: MoonrakerSimulator) =>
    [...mock.control.files.values()].filter((f) => f.root === 'gcodes')

  await page.goto(farm.origin + '/biblioteca')
  await page.getByLabel('Modo para novos envios').selectOption('server')
  await page.getByRole('button', { name: 'Alterar modo' }).click()
  await expect(
    page
      .getByRole('status')
      .filter({ hasText: 'Modo de armazenamento alterado' }),
  ).toBeVisible()
  await page
    .getByRole('button', { name: 'Enviar arquivo', exact: true })
    .click()
  const upload = page.locator('#library-upload')
  const chooser = upload.getByLabel('Arquivo (.gcode ou .3mf, até 512 MiB)')
  const send = upload.getByRole('button', { name: 'Enviar para a biblioteca' })

  await test.step('envia G-code e 3MF de 3 placas e vê metadados e miniatura', async () => {
    await chooser.setInputFiles({
      name: 'peca.gcode',
      mimeType: 'application/octet-stream',
      buffer: Buffer.from(GCODE),
    })
    await send.click()
    await expect(upload.getByText('Arquivo enviado: versão 1')).toBeVisible()
    await expect(upload.getByText('1 placa(s) no arquivo.')).toBeVisible()
    await expect(upload.getByText('10 min')).toBeVisible()
    await expect(upload.getByText(/PrusaSlicer\s*2\.7\.1/)).toBeVisible()
    await chooser.setInputFiles({
      name: 'projeto.3mf',
      mimeType: 'application/octet-stream',
      buffer: project,
    })
    await send.click()
    await expect(upload.getByText('3 placa(s) no arquivo.')).toBeVisible()
    await expect(upload.getByText('Bambu Lab X1')).toBeVisible()
    await expect(page.getByText('2 item(ns) na lista.')).toBeVisible()
    const card = (title: string) =>
      page.getByRole('article').filter({
        has: page.getByRole('heading', { name: title, exact: true }),
      })
    await expect(card('projeto').locator('img')).toBeVisible()
    await expect
      .poll(() =>
        card('projeto')
          .locator('img')
          .evaluate((img: HTMLImageElement) => img.naturalWidth),
      )
      .toBeGreaterThan(0)
    await expect(card('peca')).toContainText('PrusaSlicer')
    // The server holds both files, named by their hash.
    expect(await blobs(farm.harness.libraryDirectory)).toHaveLength(2)
  })

  await test.step('imprime o G-code em um Moonraker e termina a impressão', async () => {
    await page.getByRole('button', { name: 'Ver detalhes de peca' }).click()
    const text = await replayFromDialog(
      farm,
      page,
      () =>
        page
          .getByRole('button', { name: 'Imprimir de novo a versão v1' })
          .click(),
      'moonraker-a',
    )
    expect(text).toContain('Guardado em: Servidor')
    expect(text).toContain('Impressão iniciada')
    await expect.poll(() => a!.model().state).toBe('printing')
    expect(printed(a!)).toHaveLength(1)
    expect(printed(a!)[0]!.content.toString()).toBe(GCODE)
    expect(printed(b!)).toHaveLength(0)
    // Let the Connector observe the running job (the drift keeps snapshots
    // coming) before it ends, so the finished job keeps its library link.
    a!.update({ progress: 0.5 })
    const assignment = farm.printers[0]!
    const assignmentId = assignment.assignmentId
    if (!assignmentId) throw new Error('Expected live printer assignment')
    await expect
      .poll(
        async () => {
          const response = await page.request.get(
            `${farm.origin}/api/farms/${farm.farmId}/printer-states`,
          )
          if (!response.ok()) return false
          const body = (await response.json()) as {
            states: Array<{
              assignmentId: string
              printerKey: string
              state: string
              progress?: number
            }>
          }
          return body.states.some(
            (state) =>
              state.assignmentId === assignmentId &&
              state.printerKey === assignment.printerKey &&
              state.state === 'printing' &&
              state.progress === 0.5,
          )
        },
        { timeout: 90_000 },
      )
      .toBe(true)
    a!.update({ state: 'complete', progress: 1 })
  })

  await test.step('imprime de novo pelo Histórico em um segundo Moonraker compatível', async () => {
    await page.goto(farm.origin + '/historico')
    await expect(
      page.getByRole('heading', { name: 'Histórico de trabalhos' }),
    ).toBeVisible()
    const job = page
      .getByRole('table', { name: 'Trabalhos finalizados' })
      .getByRole('row')
      .filter({ hasText: 'moonraker-a' })
      .filter({ hasText: 'Concluído' })
    await expect(async () => {
      await page.getByRole('button', { name: 'Atualizar histórico' }).click()
      await expect(job).toHaveCount(1, { timeout: 3000 })
    }).toPass({ timeout: 90_000 })
    // The finished job links back to the library version that printed.
    await expect(job).toContainText(
      `Biblioteca · versão ${sha256(GCODE).slice(0, 12)}`,
    )
    const again = job.getByRole('button', { name: /^Imprimir de novo / })
    const text = await replayFromDialog(
      farm,
      page,
      async () => {
        await again.click()
      },
      'moonraker-b',
    )
    expect(text).toContain('Impressão iniciada')
    await expect.poll(() => b!.model().state).toBe('printing')
    expect(printed(b!)).toHaveLength(1)
    expect(printed(b!)[0]!.content.toString()).toBe(GCODE)
  })

  await test.step('mostra a recusa do 3MF, incompatível com os dois Moonraker', async () => {
    await page.goto(farm.origin + '/biblioteca')
    await page.getByRole('button', { name: 'Ver detalhes de projeto' }).click()
    await page
      .getByRole('button', { name: 'Imprimir de novo a versão v1' })
      .click()
    const dialog = page.getByRole('dialog', { name: 'Imprimir de novo' })
    const blocked = dialog.getByRole('region', {
      name: 'Bloqueadas ou indisponíveis',
    })
    await expect(blocked).toContainText('moonraker-a')
    await expect(blocked).toContainText('moonraker-b')
    await expect(blocked).toContainText(
      'O modelo de impressora indicado no arquivo é incompatível.',
    )
    await expect(dialog.getByLabel('moonraker-a')).toBeDisabled()
    await expect(dialog.getByLabel('moonraker-b')).toBeDisabled()
    await expect(
      dialog.getByRole('button', { name: 'Imprimir de novo', exact: true }),
    ).toBeDisabled()
    await dialog.getByRole('button', { name: 'Fechar' }).click()
  })

  await test.step('confirma a placa livre do primeiro Moonraker', async () => {
    // Its finished library job holds new starts until the operator confirms.
    await farm.openFarm()
    const confirm = page
      .locator('li.floor-tile')
      .filter({ hasText: 'moonraker-a' })
      .getByRole('button', { name: 'Confirmar placa livre', exact: true })
    await confirm.click({ timeout: 90_000 })
    const dialog = page.getByRole('dialog', { name: /Confirmar placa livre/ })
    await dialog
      .getByRole('button', { name: 'Confirmar placa livre', exact: true })
      .click({ timeout: 90_000 })
    await expect(dialog.getByRole('status')).toHaveText(
      'Comando confirmado pelo Connector.',
    )
    await dialog.getByRole('button', { name: 'Fechar' }).click()
    await expect(confirm).toBeHidden({ timeout: 90_000 })
    await page.goto(farm.origin + '/biblioteca')
  })

  await test.step('modo Connector: o servidor guarda só metadados e a reimpressão usa o Connector', async () => {
    await page.reload()
    await page.getByLabel('Modo para novos envios').selectOption('connector')
    await page.getByRole('button', { name: 'Alterar modo' }).click()
    await expect(
      page
        .getByRole('status')
        .filter({ hasText: 'Modo de armazenamento alterado' }),
    ).toBeVisible()
    const before = await blobs(farm.harness.libraryDirectory)
    await page
      .getByRole('button', { name: 'Enviar arquivo', exact: true })
      .click()
    await chooser.setInputFiles({
      name: 'conector.gcode',
      mimeType: 'application/octet-stream',
      buffer: Buffer.from(GCODE_CONNECTOR),
    })
    await upload
      .getByLabel('Connector de destino')
      .selectOption(farm.harness.agentId)
    await send.click()
    await expect(upload.getByText('Arquivo enviado: versão 1')).toBeVisible({
      timeout: 60_000,
    })
    await expect(upload.getByText('12 min')).toBeVisible()
    await expect(page.getByText('3 item(ns) na lista.')).toBeVisible()
    // The server stored no byte of it: same blobs as before the upload.
    expect(await blobs(farm.harness.libraryDirectory)).toEqual(before)
    await expect(
      page.getByRole('region', { name: 'Armazenamento' }),
    ).toContainText(/Connector[^\n]*: 1 arquivo\(s\)/)

    a!.update({ state: 'standby', progress: 0, filename: '' })
    await page.getByRole('button', { name: 'Ver detalhes de conector' }).click()
    const text = await replayFromDialog(
      farm,
      page,
      () =>
        page
          .getByRole('button', { name: 'Imprimir de novo a versão v1' })
          .click(),
      'moonraker-a',
    )
    expect(text).toContain('Guardado em: Connector')
    expect(text).toContain('servidor não tem cópia')
    expect(text).toContain('Impressão iniciada')
    await expect.poll(() => a!.model().state).toBe('printing')
    expect(
      printed(a!).some((f) => f.content.toString() === GCODE_CONNECTOR),
    ).toBe(true)
  })

  farm.assertNoOutbound()
})
