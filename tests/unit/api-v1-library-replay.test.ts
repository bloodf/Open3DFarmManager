const gcode = Buffer.from(
  `; generated by OrcaSlicer 2.1
; printer_model = Ender 3
; nozzle_diameter = 0.4
; filament_type = PLA
; filament used [g] = 2
; layer_height = 0.2
G1 X1
`,
)

async function asToken(
  world: ReturnType<typeof freshWorld>,
  scopes: (
    | 'library:read'
    | 'library:write'
    | 'jobs:start'
    | 'jobs:write'
    | 'jobs:read'
    | 'printers:read'
  )[],
) {
  const app = world.addApp([{ scopes }])
  return tokenFor(world, app)
}

describe('library endpoints', () => {
  it('refuses a reader that tries to upload or change the storage mode', async () => {
    const world = freshWorld()
    const token = await asToken(world, ['library:read'])
    const upload = await call({
      method: 'POST',
      path: '/library',
      token,
      body: {
        farmId: ids.farmA,
        name: 'part.gcode',
        contentBase64: gcode.toString('base64'),
      },
    })
    const patch = await call({
      method: 'PATCH',
      path: '/library/settings',
      token,
      body: { farmId: ids.farmA, storageMode: 'server' },
    })
    expect(upload.status).toBe(403)
    expect(patch.status).toBe(403)
    expect(upload.json).toMatchObject({ code: 'insufficient-scope' })
  })

  it('refuses a writer that tries to read', async () => {
    const world = freshWorld()
    const token = await asToken(world, ['library:write'])
    const listed = await call({
      method: 'GET',
      path: `/library?farmId=${ids.farmA}`,
      token,
    })
    expect(listed.status).toBe(403)
  })

  it('returns the storage mode and stores an upload in each mode', async () => {
    const world = freshWorld()
    const token = await asToken(world, ['library:read', 'library:write'])
    const before = await call({
      method: 'GET',
      path: `/library?farmId=${ids.farmA}`,
      token,
    })
    expect(before.status).toBe(200)
    expect(before.json).toMatchObject({ storageMode: 'connector' })

    const connector = await call({
      method: 'POST',
      path: '/library',
      token,
      body: {
        farmId: ids.farmA,
        name: 'connector.gcode',
        contentBase64: gcode.toString('base64'),
      },
    })
    expect(connector.status).toBe(201)
    expect(connector.json).toMatchObject({
      storageMode: 'connector',
      version: { storageLocation: 'connector' },
    })
    expect(world.library.events).toEqual([
      expect.objectContaining({
        type: 'library.version.created',
        storageMode: 'connector',
      }),
    ])
    expect(world.library.audits).toEqual([
      expect.objectContaining({
        action: 'library.changed',
        outcome: 'created',
        details: expect.objectContaining({ storageMode: 'connector' }),
      }),
    ])
    expect(world.libraryStore.bytes.size).toBe(0)

    const patched = await call({
      method: 'PATCH',
      path: '/library/settings',
      token,
      body: { farmId: ids.farmA, storageMode: 'server' },
    })
    expect(patched.json).toMatchObject({ storageMode: 'server' })
    const server = await call({
      method: 'POST',
      path: '/library',
      token,
      body: {
        farmId: ids.farmA,
        name: 'server.gcode',
        contentBase64: Buffer.from(
          gcode.toString('utf8') + '; server\n',
        ).toString('base64'),
      },
    })
    expect(server.status).toBe(201)
    expect(server.json).toMatchObject({
      storageMode: 'server',
      version: { storageLocation: 'server' },
    })
    expect(world.libraryStore.bytes.size).toBe(1)

    const itemId = (server.json as { item: { id: string } }).item.id
    const read = await call({
      method: 'GET',
      path: `/library/${itemId}`,
      token,
    })
    expect(read.status).toBe(200)
    expect(read.json).toMatchObject({ id: itemId, storageMode: 'server' })
  })

  it('hides a farm the grant does not cover', async () => {
    const world = freshWorld()
    const token = await asToken(world, ['library:read', 'library:write'])
    const listed = await call({
      method: 'GET',
      path: `/library?farmId=${ids.farmB}`,
      token,
    })
    const uploaded = await call({
      method: 'POST',
      path: '/library',
      token,
      body: {
        farmId: ids.farmB,
        name: 'part.gcode',
        contentBase64: gcode.toString('base64'),
      },
    })
    expect(listed.status).toBe(404)
    expect(uploaded.status).toBe(404)
  })
})

describe('library replay', () => {
  it('refuses a job token that cannot write a library start', async () => {
    const world = freshWorld()
    const token = await asToken(world, ['jobs:start'])
    const response = await call({
      method: 'POST',
      path: `/printers/${ids.printerA1}/jobs`,
      token,
      headers: { 'idempotency-key': 'replay-denied' },
      body: { libraryVersionId: ids.versionA },
    })
    expect(response.status).toBe(403)
    expect(response.json).toMatchObject({ code: 'insufficient-scope' })
  })

  it('starts a replay from either storage mode and refuses another farm', async () => {
    const world = freshWorld()
    const token = await asToken(world, ['jobs:start', 'jobs:write'])
    for (const versionId of [ids.versionA, ids.versionServer]) {
      const response = await call({
        method: 'POST',
        path: `/printers/${ids.printerA1}/jobs`,
        token,
        headers: { 'idempotency-key': `replay-${versionId}` },
        body: { libraryVersionId: versionId },
      })
      expect(response.status).toBe(202)
      const job = response.json as {
        id: string
        libraryVersionId: string
        storageMode: string
        status: string
      }
      expect(job).toMatchObject({
        libraryVersionId: versionId,
        status: 'queued',
      })
      expect(['server', 'connector']).toContain(job.storageMode)
      const command = [...world.envelopes.commands.values()].find(
        (entry) => entry.kind === 'action',
      )
      expect(command).toMatchObject({
        kind: 'action',
        action: { action: 'start_library_print' },
      })
    }
    const otherFarm = await call({
      method: 'POST',
      path: `/printers/${ids.printerB1}/jobs`,
      token,
      headers: { 'idempotency-key': 'other-farm' },
      body: { libraryVersionId: ids.versionA },
    })
    expect(otherFarm.status).toBe(404)
    expect(world.library.audits).toEqual(
      expect.arrayContaining([
        expect.objectContaining({
          details: expect.objectContaining({ status: 'replay' }),
        }),
      ]),
    )
  })

  it('records the Connector refusal when the printer cannot print the file', async () => {
    const starter = createLibraryPrintStarter({
      cache: {
        acquire: async () => {
          throw new Error('unused')
        },
      },
      download: async () => {
        throw new Error('unused')
      },
      profile: async () => undefined,
    } as never)
    const refused = await starter.start({
      args: { sha256: 'ab'.repeat(32), plate: 1 },
      target: { backend: 'moonraker', origin: 'http://127.0.0.1:9' } as never,
      signal: new AbortController().signal,
      authorize: () => true,
      start: async () => {},
    })
    expect(refused).toMatchObject({ ok: false, code: 'incompatible' })

    const world = freshWorld()
    const token = await asToken(world, [
      'jobs:start',
      'jobs:write',
      'jobs:read',
    ])
    const submitted = await call({
      method: 'POST',
      path: `/printers/${ids.printerA1}/jobs`,
      token,
      headers: { 'idempotency-key': 'incompatible' },
      body: { libraryVersionId: ids.versionServer, plate: 1 },
    })
    expect(submitted.status).toBe(202)
    const jobId = (submitted.json as { id: string }).id
    const envelope = [...world.envelopes.rows.values()].find(
      (row) => row.resourceId === jobId,
    )
    expect(envelope?.requiredScope).toBe('jobs:write')
    if (!envelope) throw new Error('missing envelope')
    envelope.status = 'refused'
    envelope.refusalCode = 'not-ready'
    envelope.resultDetail = 'incompatible'
    const read = await call({
      method: 'GET',
      path: `/jobs/${jobId}`,
      token,
    })
    expect(read.status).toBe(200)
    expect(read.json).toMatchObject({
      status: 'refused',
      refusal: { code: 'not-ready', detail: 'incompatible' },
    })
  })
})
