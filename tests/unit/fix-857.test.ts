it('relays a Connector-mode G-code upload to the Connector and verifies it', async () => {
  const farmId = randomUUID()
  const agentId = randomUUID()
  const received: Buffer[] = []
  const put = vi
    .spyOn(connectorLibraryRelay, 'put')
    .mockImplementation(async (input) => {
      for await (const chunk of input.body) received.push(Buffer.from(chunk))
      const bytes = Buffer.concat(received)
      return { sha256: sha(bytes), size: bytes.length, created: true }
    })
  const store = new PostgresIntegrationLibrary(undefined as never)
  await store.retain(hash, gcode, 'connector', { farmId, agentId })
  expect(put).toHaveBeenCalledWith(
    expect.objectContaining({ farmId, agentId, maxBytes: gcode.length }),
  )
  expect(Buffer.concat(received)).toEqual(gcode)

  put.mockResolvedValue({
    sha256: '0'.repeat(64),
    size: gcode.length,
    created: true,
  })
  await expect(
    store.retain(hash, gcode, 'connector', { farmId, agentId }),
  ).rejects.toThrow('Library storage unavailable')
})

it.skipIf(!postgresReady)(
  'uploads, approves and replays a server-mode G-code version through the Connector download',
  async () => {
    const database = disposablePostgres({
      ...vitestPostgresOptions('openfarm-fix-857'),
      isolated: true,
    })
    cleanups.push(() => database.stop())
    const sql = await database.start()
    const now = Date.now()

    const owner = `owner_${randomUUID().replaceAll('-', '')}`
    const farm = randomUUID()
    const agent = randomUUID()
    const printer = randomUUID()
    const app = randomUUID()
    const grant = randomUUID()

    // The Connector's enrolled key and the credential the server issued to it.
    const issuer = await crypto.subtle.generateKey('Ed25519', false, [
      'sign',
      'verify',
    ])
    const pair = await crypto.subtle.generateKey('Ed25519', true, [
      'sign',
      'verify',
    ])
    const publicKeySpki = Buffer.from(
      await crypto.subtle.exportKey('spki', pair.publicKey),
    ).toString('base64url')
    const identity = new ConnectorIdentity(KeyObject.from(pair.privateKey))
    const policy = {
      issuer: 'https://farm.test',
      audience: 'connector-telemetry',
      ttlSeconds: 600,
    }
    const deviceToken = await issueConnectorCredential({
      ...policy,
      kid: 'k1',
      privateKey: issuer.privateKey,
      agentId: agent,
      farmId: farm,
      publicKeySpki,
      nowSeconds: Math.floor(now / 1000),
      jti: randomUUID(),
    })

    await sql`INSERT INTO farm.session_accounts (id) VALUES (${owner})`
    await sql`INSERT INTO farm.farms (id, sandbox) VALUES (${farm}, false)`
    await sql`INSERT INTO farm.memberships (farm_id, account_id, role) VALUES (${farm}, ${owner}, 'owner')`
    await sql`INSERT INTO farm.connector_enrollments (agent_id, farm_id, public_key_spki, fingerprint)
      VALUES (${agent}, ${farm}, ${publicKeySpki}, ${'fix-857'.padEnd(50, 'f')})`
    await sql`UPDATE farm.connector_enrollments SET status = 'approved' WHERE agent_id = ${agent}`
    await sql`INSERT INTO farm.printer_assignments (id, farm_id, agent_id, printer_key, created_at, created_by)
      VALUES (${printer}, ${farm}, ${agent}, 'fix-857-fixture', 1, ${owner})`
    await sql`INSERT INTO farm.integration_apps (id, farm_id, name, sandbox, created_at, created_by)
      VALUES (${app}, ${farm}, 'fix 857 fixture', false, 1, ${owner})`
    await sql`INSERT INTO farm.integration_app_grants
      (id, app_id, farm_id, printer_assignment_id, scopes, requires_approval, created_at, created_by)
      VALUES (${grant}, ${app}, ${farm}, ${printer}, ARRAY['jobs:start','jobs:write'], true, 1, ${owner})`

    const grantFields = { appId: app, createdAt: now, disabledAt: null }
    const principal: IntegrationPrincipal = {
      appId: app,
      scopes: ['library:read', 'library:write', 'jobs:start', 'jobs:write'],
      grants: [
        {
          ...grantFields,
          id: randomUUID(),
          farmId: farm,
          printerAssignmentId: null,
          scopes: ['library:read', 'library:write'],
          requiresApproval: false,
          disabledReason: null,
        },
        {
          ...grantFields,
          id: grant,
          farmId: farm,
          printerAssignmentId: printer,
          scopes: ['jobs:start', 'jobs:write'],
          requiresApproval: true,
          disabledReason: null,
        },
      ],
    }
    const library = new IntegrationLibraryService(
      new PostgresIntegrationLibrary(sql),
    )
    state.service = library
    expect(await library.setSettings(principal, farm, 'server')).toMatchObject({
      ok: true,
    })

    const upload = () =>
      uploadIntegrationLibrary(
        new Request('https://farm.test/api/integrations/v1/library', {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify({
            farmId: farm,
            name: 'part.gcode',
            contentBase64: gcode.toString('base64'),
          }),
        }),
        principal,
      ) as Promise<Response>
    const uploaded = await upload()
    expect(uploaded.status).toBe(201)
    const { version } = (await uploaded.json()) as {
      version: { id: string; sha256: string }
    }
    expect(version.sha256).toBe(hash)
    const blobs = await createBlobStore(serverDirectory)
    expect(await blobs.has(hash)).toBe(true)

    // Uploading the same bytes again restores a version that has no file
    // (every G-code version stored before this fix).
    await blobs.remove(hash)
    expect(await (await upload()).json()).toMatchObject({
      deduplicated: true,
      version: { id: version.id },
    })
    expect(await blobs.has(hash)).toBe(true)

    const deliveryStore = new PostgresIntegrationDelivery(sql)
    const sent: string[] = []
    const delivery = new IntegrationDeliveryService({
      store: deliveryStore,
      inbox: {
        sendToAgentInbox(_farm, _agent, wire) {
          sent.push(wire)
          return 'sent'
        },
      },
      audit: new IntegrationAuditService(new PostgresIntegrationAudit(sql)),
      signer: { kid: 'fix-857', signingKey: issuer.privateKey },
    })
    const envelopes = {
      issue: (input: Parameters<typeof delivery.issue>[0]) =>
        delivery.issue(input),
      deliver: (id: string) => delivery.deliver(id),
      get: (id: string) => deliveryStore.get(id),
    }
    const jobs = new IntegrationJobsService({
      store: new PostgresIntegrationJobs(sql),
      library,
      envelopes,
    })
    const submitted = await jobs.submit(principal, printer, 'fix-857-replay', {
      libraryVersionId: version.id,
    })
    if (!submitted.ok) throw new Error(submitted.problem)
    expect(submitted.job).toMatchObject({ status: 'held' })
    expect(sent).toEqual([])

    const approvals = new IntegrationApprovalService({
      store: new PostgresIntegrationApprovals(sql),
      envelopes,
    })
    expect(
      await approvals.decide(owner, farm, submitted.job.id, 'approve'),
    ).toMatchObject({ ok: true })
    const { envelope } = decodeApiEnvelopeFrame(sent[0]!)
    expect(envelope.kind).toBe('action')
    const command = envelope as unknown as {
      action: { action: string; args: { sha256: string } }
    }
    expect(command.action).toMatchObject({
      action: 'start_library_print',
      args: { sha256: hash },
    })

    // The server side as the Nitro plugin composes it, behind HTTPS.
    const records = new PostgresConnectorLibraryDownloads(sql)
    const download = startConnectorLibraryDownload({
      credentials: {
        ...policy,
        publicKeys: new Map([['k1', issuer.publicKey]]),
      },
      enrollments: records,
      findBlob: (farmId, sha256) => records.findBlob(farmId, sha256),
      audit: (entry) => records.audit(entry),
      blobs,
    })
    cleanups.push(() => download.stop())
    const server: Server = createServer({ cert, key }, async (req, res) => {
      const headers = new Headers()
      for (const [name, value] of Object.entries(req.headers))
        if (typeof value === 'string') headers.set(name, value)
      const answer = await connectorLibraryDownload()!(
        req.url!.split('/').at(-1)!,
        headers,
      )
      res.writeHead(answer.status, answer.headers)
      if (answer.body instanceof Readable) answer.body.pipe(res)
      else res.end(JSON.stringify(answer.body))
    })
    await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve))
    cleanups.push(() => new Promise((resolve) => server.close(resolve)))
    const origin = `https://localhost:${(server.address() as AddressInfo).port}`

    const proof = () => ({
      authorization: `Bearer ${deviceToken}`,
      'x-connector-agent': agent,
      'x-connector-farm': farm,
      ...identity.signLibraryProof({
        token: deviceToken,
        agentId: agent,
        farmId: farm,
        now: Date.now(),
      }),
    })
    const fetchFile = createHttpsLibraryDownloader({
      baseUrl: origin,
      headers: proof,
      ca: cert,
    })
    const parts: Uint8Array[] = []
    for await (const part of (await fetchFile(hash, signal)).stream)
      parts.push(part)
    const received = Buffer.concat(parts)
    expect(received).toEqual(gcode)
    expect(sha(received)).toBe(hash)

    const connector = async () =>
      (await createConnectorLibrary({
        endpoint: `${origin}/api/connector/telemetry`,
        credential: {
          device_token: deviceToken,
          farm_id: farm,
          agent_id: agent,
        },
        identity,
        dataDirectory: await directory('fix-857-connector-'),
        ca: cert,
      }))!
    const mock = await startMoonrakerMock()
    cleanups.push(() => mock.close())
    const starts: string[] = []
    const replay = async (authorize = () => true) =>
      (await connector())
        .starterFor(async () => ({
          model: 'Printer One',
          nozzleDiameters: [0.4],
        }))
        .start({
          args: command.action.args,
          target: { backend: 'moonraker', origin: mock.origin },
          signal,
          authorize,
          start: async (name) => void starts.push(name),
        })

    // A printer that is not ready is refused before anything is fetched.
    await expect(replay(() => false)).rejects.toThrow('unauthorized')
    expect(starts).toEqual([])

    expect(await replay()).toMatchObject({ ok: true, source: 'download' })
    expect(starts).toEqual([`${hash.slice(0, 16)}.gcode`])

    // A missing file keeps the existing answer, and nothing is started.
    await blobs.remove(hash)
    const missing = await connectorLibraryDownload()!(
      hash,
      new Headers(proof()),
    )
    expect(missing).toMatchObject({
      status: 404,
      body: { error: 'Arquivo não encontrado.' },
    })
    expect(await replay()).toMatchObject({
      ok: false,
      code: 'download-failed',
    })
    expect(starts).toHaveLength(1)
  },
  60_000,
)

it('reports a disabled library runtime clearly', async () => {
  state.enabled = false
  state.service = {
    upload: async () => ({ ok: false, problem: 'service-unavailable' }),
  }
  try {
    const response = (await uploadIntegrationLibrary(
      new Request('https://farm.test/api/integrations/v1/library', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({
          farmId: randomUUID(),
          name: 'part.gcode',
          contentBase64: gcode.toString('base64'),
        }),
      }),
      {} as IntegrationPrincipal,
    )) as Response
    expect(response.status).toBe(503)
    expect(await response.json()).toMatchObject({
      code: 'service-unavailable',
      errors: [{ detail: 'Biblioteca desativada nesta instalação.' }],
    })
  } finally {
    state.enabled = true
  }
})

