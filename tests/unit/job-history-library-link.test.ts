const printerKey = 'printer-1'
const body = Buffer.from(
  '; generated by PrusaSlicer 2.8.0\n; printer_model = Printer One\nG28\n',
)
const sha256 = createHash('sha256').update(body).digest('hex')
const uploaded = `${sha256.slice(0, 16)}.gcode`

/** Real directory under the worktree's ignored `.data/`. */
async function directory(prefix: string) {
  await mkdir(join(process.cwd(), '.data'), { recursive: true })
  return mkdtemp(join(process.cwd(), '.data', prefix))
}

function state(
  over: Partial<PrinterState> & Pick<PrinterState, 'state'>,
): PrinterState {
  return PrinterState.parse({ printerKey, observedAt: 1000, ...over })
}
const printing = () => state({ state: 'printing', progress: 0.4 })
const finished = (lastJob: Record<string, unknown>) =>
  state({ state: 'idle', progress: 1, lastJob })
const event = (printer: PrinterState): TelemetryEvent => ({
  eventId: crypto.randomUUID(),
  queuedAt: 1,
  kind: 'printer-state',
  state: printer,
})

/** Fake transaction that records every INSERT it is asked to run. */
function fakeTransaction() {
  const inserts: { sql: string; values: unknown[] }[] = []
  const tx = (async (strings: TemplateStringsArray, ...values: unknown[]) => {
    inserts.push({ sql: strings.join('?'), values })
    return []
  }) as unknown as TransactionSql
  return { tx, inserts }
}
const scope = {
  farmId: '3f0f8b7e-6a43-4f6e-9d3a-0b6a8f1f2c11',
  agentId: '9a1b2c3d-4e5f-4a6b-8c7d-0e1f2a3b4c5d',
}

describe('library start then completion (E16 Moonraker mock)', () => {
  test('records the printed hash and plate in job history', async () => {
    const mock = await startMoonrakerMock()
    try {
      const starter = createLibraryPrintStarter({
        cache: await createLibraryCache({
          directory: await directory('job-link-cache-'),
          maxBytes: 1_000_000,
        }),
        download: async () => ({
          size: body.length,
          stream: (async function* () {
            yield body
          })(),
        }),
        profile: async () => ({ model: 'Printer One', nozzleDiameters: [0.4] }),
      })
      const links = createLibraryJobLinks()
      const started: string[] = []
      const result = await starter.start({
        args: { sha256 },
        target: { backend: 'moonraker', origin: mock.origin },
        signal: new AbortController().signal,
        authorize: () => true,
        start: async (name) => {
          started.push(name)
        },
      })
      expect(result).toMatchObject({ ok: true, name: uploaded })
      expect(mock.control.files.has(uploaded)).toBe(true)
      // What the API command runner does once the start reached the printer.
      if (result.ok)
        links.remember(printerKey, { name: result.name, sha256, plate: 2 })

      const events = [
        links.attach(printing()),
        links.attach(
          finished({
            outcome: 'completed',
            filename: uploaded,
            printDuration: 60,
            endedAt: 5000,
          }),
        ),
        // `lastJob` repeats until the next print ends; the link repeats with it.
        links.attach(
          finished({
            outcome: 'completed',
            filename: uploaded,
            printDuration: 60,
            endedAt: 5000,
          }),
        ),
      ].map(event)
      const jobs = jobsFromEvents(events)
      expect(jobs).toEqual([
        {
          printerKey,
          outcome: 'completed',
          filename: uploaded,
          printDurationSeconds: 60,
          librarySha256: sha256,
          plate: 2,
          endedAt: 5000,
        },
      ])
      const { tx, inserts } = fakeTransaction()
      await recordJobs(tx, scope, jobs)
      expect(inserts).toHaveLength(1)
      expect(inserts[0]!.sql).toContain('library_sha256, plate')
      expect(inserts[0]!.values).toContain(sha256)
      expect(inserts[0]!.values).toContain(2)
    } finally {
      await mock.close()
    }
  })
})

describe('unlinked jobs stay unchanged', () => {
  const plain = {
    outcome: 'completed',
    filename: 'benchy.gcode',
    printDuration: 90,
    endedAt: 7000,
  }
  test('a job started outside the library has no link', () => {
    const links = createLibraryJobLinks()
    links.remember(printerKey, { name: uploaded, sha256 })
    links.attach(printing())
    const out = links.attach(finished(plain))
    expect(out.lastJob).toEqual(plain)
    expect(jobsFromEvents([event(out)])[0]).not.toHaveProperty('librarySha256')
  })

  test('a job imported from printer history is never linked', () => {
    const links = createLibraryJobLinks()
    links.remember(printerKey, { name: uploaded, sha256 })
    // Imported rows arrive idle with a matching name but without a run seen.
    const out = links.attach(finished({ ...plain, filename: uploaded }))
    expect(out.lastJob?.sha256).toBeUndefined()
  })

  test('the previous job repeated while the new one runs never claims the start', () => {
    const links = createLibraryJobLinks()
    const previous = { ...plain, filename: uploaded, endedAt: 1 }
    links.remember(printerKey, { name: uploaded, sha256 })
    const whileRunning = links.attach(
      state({ state: 'printing', progress: 0.1, lastJob: previous }),
    )
    expect(whileRunning.lastJob?.sha256).toBeUndefined()
    const done = links.attach(finished({ ...previous, endedAt: 9000 }))
    expect(done.lastJob?.sha256).toBe(sha256)
  })

  test('one start links one job only', () => {
    const links = createLibraryJobLinks()
    links.remember(printerKey, { name: uploaded, sha256 })
    links.attach(printing())
    links.attach(finished({ ...plain, filename: uploaded, endedAt: 8000 }))
    links.attach(printing())
    const next = links.attach(
      finished({ ...plain, filename: uploaded, endedAt: 9000 }),
    )
    expect(next.lastJob?.sha256).toBeUndefined()
  })

  test('records and rows without a link keep their shape', async () => {
    const jobs = jobsFromEvents([event(finished(plain))])
    expect(jobs).toEqual([
      {
        printerKey,
        outcome: 'completed',
        filename: 'benchy.gcode',
        printDurationSeconds: 90,
        endedAt: 7000,
      },
    ])
    const { tx, inserts } = fakeTransaction()
    await recordJobs(tx, scope, jobs)
    expect(inserts[0]!.values.slice(-3)).toEqual([null, null, 7000])
    const row = jobHistoryRow({ id: '1', ...jobs[0]! })
    expect(row.library).toBe('Fora da biblioteca')
  })

  test('a malformed link is dropped, never stored', () => {
    expect(jobLibraryLink({ sha256: 'ABC', plate: 2 })).toBeUndefined()
    expect(jobLibraryLink({ plate: 2 })).toBeUndefined()
    expect(jobLibraryLink({ sha256, plate: 0 })).toEqual({
      librarySha256: sha256,
    })
    expect(
      PrinterState.safeParse({
        printerKey,
        state: 'idle',
        observedAt: 1,
        lastJob: { outcome: 'completed', endedAt: 1, sha256: 'xyz' },
      }).success,
    ).toBe(false)
  })
})

