describe('migration 0061 round trip', () => {
  const dir = join(process.cwd(), 'infra/db/migrations')
  const added = (sql: string) =>
    [...sql.matchAll(/ADD COLUMN (\w+) (\w+)/g)].map((m) => [m[1], m[2]])
  const dropped = (sql: string) =>
    [...sql.matchAll(/DROP COLUMN (\w+)/g)].map((m) => m[1])

  test('up is expand-only and nullable; down removes exactly what up added', async () => {
    const up = await readFile(
      join(dir, '0061_job_library_version.up.sql'),
      'utf8',
    )
    const down = await readFile(
      join(dir, '0061_job_library_version.down.sql'),
      'utf8',
    )
    expect(findDestructiveOperations(stripSqlCommentsAndStrings(up))).toEqual(
      [],
    )
    expect(added(up)).toEqual([
      ['library_sha256', 'text'],
      ['plate', 'integer'],
    ])
    expect(up).not.toMatch(/NOT NULL|DEFAULT/i)
    expect(new Set(dropped(down))).toEqual(new Set(added(up).map(([n]) => n)))
    // Applying up then down restores the earlier column set.
    const columns = new Set(['id', 'printer_key', 'filament_usage'])
    for (const [name] of added(up)) columns.add(name!)
    for (const name of dropped(down)) columns.delete(name!)
    expect([...columns]).toEqual(['id', 'printer_key', 'filament_usage'])
  })
})
