describe('Connector library mode, server runtime and Connector agent composed', () => {
  test('the library runtime carries the relay, so Connector uploads are no longer refused', async () => {
    const w = await world()
    expect(w.runtime.relay).toBe(connectorLibraryRelay)
    expect(w.runtime.blobs).toBeUndefined()
  })

  test('upload stores the bytes only on the Connector; the server keeps metadata', async () => {
    const w = await world()
    const file = gcode('first')
    const hash = sha(file)

    const response = await w.upload('piece.gcode', file)
    expect(response.status).toBe(201)
    expect(response.body['version']).toMatchObject({
      sha256: hash,
      sizeBytes: file.length,
      storageLocation: 'connector',
      agentId: w.agentId,
      metadata: { printerModel: 'Printer One' },
    })
    // The file lives in the Connector host's configured directory, intact.
    expect(await stored(w.hostLibrary)).toEqual([hash])
    // The server side holds no file bytes: no blob store, and rows carry no content.
    expect(w.runtime.blobs).toBeUndefined()
    expect(JSON.stringify(w.memory.versions)).not.toContain('G1 X10 Y10')
    expect(w.diagnostics).toEqual([])
  })

  test('list and search work from server metadata', async () => {
    const w = await world()
    await w.upload('one.gcode', gcode('one', 'Printer One'))
    await w.upload('two.gcode', gcode('two', 'Printer Two'))

    const all = await w.route('list', { farmId: w.farmId }, { method: 'GET' })
    expect(all.status).toBe(200)
    expect(all.body['items']).toHaveLength(2)

    const found = await w.route(
      'list',
      { farmId: w.farmId },
      { method: 'GET', query: '?printerModel=Printer%20Two' },
    )
    expect(found.body['items']).toHaveLength(1)
    expect(found.body['items'][0].latest.metadata.printerModel).toBe(
      'Printer Two',
    )
  })

  test('the same bytes uploaded twice keep one file on the Connector', async () => {
    const w = await world()
    const file = gcode('same')
    const first = await w.upload('a.gcode', file)
    const second = await w.upload('b.gcode', file)
    expect(first.status).toBe(201)
    expect(second.status).toBe(201)
    expect(second.body['deduplicated']).toBe(true)
    expect(await stored(w.hostLibrary)).toEqual([sha(file)])
  })

  test('file content is reached through the Connector by range, verified by hash', async () => {
    const w = await world()
    const file = gcode('read')
    await w.upload('read.gcode', file)
    const range = await connectorLibraryRelay.read({
      farmId: w.farmId,
      agentId: w.agentId,
      sha256: sha(file),
      offset: 100,
      length: 5_000,
    })
    expect(Buffer.from(range).equals(file.subarray(100, 5_100))).toBe(true)
    await expect(
      connectorLibraryRelay.read({
        farmId: w.farmId,
        agentId: w.agentId,
        sha256: 'f'.repeat(64),
        offset: 0,
        length: 10,
      }),
    ).rejects.toThrow()
  })

  test('delete hides the version; the retention purge then removes the Connector copy', async () => {
    const w = await world()
    const file = gcode('delete')
    const hash = sha(file)
    const uploaded = await w.upload('gone.gcode', file)
    const versionId = uploaded.body['version'].id as string

    const deleted = await w.route(
      'delete',
      { farmId: w.farmId, versionId },
      { method: 'DELETE' },
    )
    expect(deleted.status).toBe(200)
    const listed = await w.route(
      'list',
      { farmId: w.farmId },
      { method: 'GET' },
    )
    expect(listed.body['items']).toHaveLength(0)
    // Soft delete keeps the file for the retention window.
    expect(await stored(w.hostLibrary)).toEqual([hash])

    // What the retention job calls for a Connector-mode blob once the window ends.
    const removed = await connectorLibraryRelay.purge(w.agentId, [hash])
    expect(removed).toEqual([hash])
    expect(await stored(w.hostLibrary)).toEqual([])
  })

  test('a file that does not fit the Connector quota is refused and nothing is kept', async () => {
    const w = await world({ quotaBytes: 10_000 })
    const response = await w.upload('big.gcode', gcode('big'))
    expect(response.status).toBe(507)
    expect(w.memory.uploads).toBe(0)
    expect(await stored(w.hostLibrary)).toEqual([])
  })

  test('a file the parser rejects leaves no orphan on the Connector', async () => {
    const w = await world()
    const response = await w.upload('bad.3mf', Buffer.from('not a zip'))
    expect(response.status).toBe(422)
    expect(w.memory.uploads).toBe(0)
    expect(await stored(w.hostLibrary)).toEqual([])
  })

  test('with no Connector polling, an upload answers 503 and nothing is stored', async () => {
    const w = await world({ connectorOnline: false })
    const response = await w.upload('offline.gcode', gcode('offline'))
    expect(response.status).toBe(503)
    expect(w.memory.uploads).toBe(0)
    expect(await stored(w.hostLibrary)).toEqual([])
  })
})
