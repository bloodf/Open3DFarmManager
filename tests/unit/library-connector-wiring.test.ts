// ---- an in-memory metadata store: the only thing the server keeps ----------

class MemoryLibrary {
  items: { id: string; title: string; createdAt: number }[] = []
  versions: Record<string, unknown>[] = []
  uploads = 0
  // No upload here shares its bytes with a record.
  discardUnused = async (_file: unknown, discard: () => Promise<void>) =>
    discard()
  uploadContext = async () => ({
    ok: true as const,
    settings: {
      storageMode: 'connector' as const,
      quotaBytes: 21_474_836_480,
      retentionDays: 30,
      keepVersions: null,
    },
  })
  addVersion = async (input: {
    version: {
      title?: string
      sha256: string
      sizeBytes: number
      agentId?: string
      metadata: { printerModel?: string }
    } & Record<string, unknown>
  }) => {
    this.uploads++
    const v = input.version
    const duplicate = this.versions.some((x) => x['sha256'] === v.sha256)
    const item = {
      id: randomUUID(),
      title: v.title ?? 'item',
      tags: [],
      archived: false,
      createdAt: this.items.length + 1,
    }
    this.items.push(item)
    const version = {
      id: randomUUID(),
      itemId: item.id,
      versionNumber: 1,
      sha256: v.sha256,
      sizeBytes: v.sizeBytes,
      storageLocation: 'connector',
      agentId: v.agentId ?? null,
      originalName: v['originalName'],
      kind: v['kind'],
      plateCount: v['plateCount'],
      metadata: v.metadata,
      hasThumbnail: false,
      notes: '',
      uploadedBy: 'owner',
      createdAt: item.createdAt,
      deletedAt: null,
      purgedAt: null,
    }
    this.versions.push(version)
    return {
      ok: true as const,
      item,
      version,
      deduplicated: duplicate,
      orphanedServerCopy: false,
    }
  }
  searchItems = async (input: { search?: { printerModel?: string } }) => ({
    ok: true as const,
    items: this.versions
      .filter((v) => v['deletedAt'] === null)
      .filter(
        (v) =>
          !input.search?.printerModel ||
          (v['metadata'] as { printerModel?: string }).printerModel ===
            input.search.printerModel,
      )
      .map((v) => ({
        ...this.items.find((i) => i.id === v['itemId'])!,
        latest: v,
      })),
    next: null,
  })
  softDeleteVersion = async (input: { versionId: string }) => {
    const version = this.versions.find((v) => v['id'] === input.versionId)
    if (!version) return { ok: false as const, reason: 'not-found' as const }
    version['deletedAt'] = 1_000
    return { ok: true as const, deletedAt: 1_000 }
  }
}

// ---- the world: relay endpoints on 127.0.0.1:0, one enrolled Connector -----

const cleanups: (() => Promise<void> | void)[] = []
afterEach(async () => {
  for (const cleanup of cleanups.splice(0).reverse()) await cleanup()
})

async function directory(prefix: string) {
  await mkdir(join(process.cwd(), '.data'), { recursive: true })
  return mkdtemp(join(process.cwd(), '.data', prefix))
}
const stored = async (dir: string) =>
  (await readdir(dir).catch(() => [])).filter((name) =>
    /^[0-9a-f]{64}$/.test(name),
  )

async function world(
  options: { connectorOnline?: boolean; quotaBytes?: number } = {},
) {
  const issuer = await crypto.subtle.generateKey('Ed25519', true, [
    'sign',
    'verify',
  ])
  const pair = await crypto.subtle.generateKey('Ed25519', true, [
    'sign',
    'verify',
  ])
  const publicKeySpki = Buffer.from(
    await crypto.subtle.exportKey('spki', pair.publicKey),
  ).toString('base64url')
  const farmId = randomUUID()
  const agentId = randomUUID()
  const policy = {
    issuer: 'https://farm.test',
    audience: 'connector-telemetry',
    ttlSeconds: 600,
    publicKeys: new Map([['k1', issuer.publicKey]]),
  }
  const device_token = await issueConnectorCredential({
    ...policy,
    kid: 'k1',
    privateKey: issuer.privateKey,
    agentId,
    farmId,
    publicKeySpki,
    nowSeconds: Math.floor(Date.now() / 1000),
    jti: randomUUID(),
  })

  const relay = startConnectorLibraryRelay({
    credentials: policy,
    enrollments: {
      find: async (farm, agent) =>
        farm === farmId && agent === agentId
          ? { status: 'approved', publicKeySpki }
          : null,
    },
    pollMs: 500,
    // The host's storage report; its recording is covered by library-retention-links-wiring.
    recordStorage: async () => true,
    claimMs: 700,
  })
  cleanups.push(() => relay.stop())

  // The Nitro route files themselves, behind a plain HTTPS adapter.
  const server: Server = createServer({ cert, key }, async (req, res) => {
    const url = new URL(req.url ?? '/', 'https://127.0.0.1')
    const headers = new Headers()
    for (const [name, value] of Object.entries(req.headers))
      if (typeof value === 'string') headers.set(name, value)
    const request = new Request(url, {
      method: req.method ?? 'GET',
      headers,
      ...(req.method === 'GET'
        ? {}
        : {
            body: Readable.toWeb(req) as ReadableStream,
            duplex: 'half',
          }),
    } as RequestInit)
    const op =
      /^\/api\/connector\/library\/relay\/([^/]+)\/(body|result)$/.exec(
        url.pathname,
      )
    const event = { req: request, context: { params: { opId: op?.[1] } } }
    const handler =
      url.pathname === '/api/connector/library/relay/poll'
        ? pollRoute
        : url.pathname === '/api/connector/library/relay/storage'
          ? storageRoute
          : op?.[2] === 'body'
            ? bodyRoute
            : op?.[2] === 'result'
              ? resultRoute
              : undefined
    const response = handler
      ? ((await (handler as unknown as (e: unknown) => unknown)(
          event,
        )) as Response)
      : new Response(null, { status: 404 })
    res.writeHead(response.status, Object.fromEntries(response.headers))
    if (response.body) Readable.fromWeb(response.body as never).pipe(res)
    else res.end()
  })
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve))
  cleanups.push(async () => {
    server.closeAllConnections()
    await new Promise((resolve) => server.close(resolve))
  })
  const port = (server.address() as AddressInfo).port

  // The Connector, composed the way the agent composes it: from configuration.
  const dataDirectory = await directory('library-wiring-')
  const hostLibrary = join(dataDirectory, 'host-library')
  const controller = new AbortController()
  cleanups.push(() => controller.abort())
  const library = await createConnectorLibrary({
    endpoint: `https://localhost:${port}/api/connector/telemetry`,
    credential: { device_token, farm_id: farmId, agent_id: agentId },
    identity: new ConnectorIdentity(KeyObject.from(pair.privateKey)),
    dataDirectory,
    ca: cert,
    library: {
      directory: hostLibrary,
      ...(options.quotaBytes ? { quotaBytes: options.quotaBytes } : {}),
    },
  })
  expect(library).toBeDefined()
  const diagnostics: string[] = []
  const serving =
    options.connectorOnline === false
      ? Promise.resolve()
      : library!.serveRelay(controller.signal, (event) =>
          diagnostics.push(event.reason),
        )
  cleanups.push(async () => {
    controller.abort()
    await serving
  })

  // The server runtime: the real `libraryRuntime()` with only the metadata store swapped.
  const runtime = await libraryRuntime()
  cleanups.push(async () => {
    const { closeLibraryRuntime } =
      await import('../../apps/farm/server/utils/library/runtime.ts')
    await closeLibraryRuntime()
  })
  const memory = new MemoryLibrary()
  const wired: LibraryRuntime = {
    ...runtime,
    store: memory as unknown as LibraryStore,
  }

  async function route(
    op: Parameters<typeof libraryRoutes>[1],
    target: Parameters<typeof libraryRoutes>[2],
    request: { method: string; query?: string; body?: Buffer },
  ) {
    const event = {
      req: new Request(
        `${origin}/api/farms/${farmId}/library${request.query ?? ''}`,
        {
          method: request.method,
          headers: {
            cookie: 'session=owner',
            origin,
            ...(request.body
              ? { 'content-type': 'application/octet-stream' }
              : {}),
          },
          ...(request.body ? { body: request.body } : {}),
        } as RequestInit,
      ),
      res: { headers: new Headers(), status: undefined as number | undefined },
    } as unknown as Parameters<typeof libraryRoutes>[0]
    try {
      const body = await libraryRoutes(event, op, target, {
        auth,
        runtime: wired,
      })
      return {
        status: (event.res as { status?: number }).status ?? 200,
        body: body as Record<string, any>, // eslint-disable-line @typescript-eslint/no-explicit-any
      }
    } catch (error) {
      const { status = 500 } = error as { status?: number }
      return { status, body: {} as Record<string, any> } // eslint-disable-line @typescript-eslint/no-explicit-any
    }
  }
  const upload = (name: string, data: Buffer) =>
    route(
      'upload',
      { farmId },
      {
        method: 'POST',
        query: `?name=${encodeURIComponent(name)}&agentId=${agentId}`,
        body: data,
      },
    )

  return {
    farmId,
    agentId,
    hostLibrary,
    memory,
    runtime,
    route,
    upload,
    diagnostics,
  }
}

