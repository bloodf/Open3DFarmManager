const cert = readFileSync(
  join(process.cwd(), 'tests/fixtures/bambu-ftps/cert.pem'),
)
const key = readFileSync(
  join(process.cwd(), 'tests/fixtures/bambu-ftps/key.pem'),
)
const signal = new AbortController().signal
const profile = { model: 'Printer One', nozzleDiameters: [0.4] }
const sha = (data: Buffer | string) =>
  createHash('sha256').update(data).digest('hex')
const gcode = Buffer.from(
  `; generated by PrusaSlicer 2.8.0\n; printer_model = Printer One\nG28\n${'G1 X10 Y10\n'.repeat(40)}`,
)
const hash = sha(gcode)

async function directory(prefix: string) {
  await mkdir(join(process.cwd(), '.data'), { recursive: true })
  return mkdtemp(join(process.cwd(), '.data', prefix))
}

const cleanups: (() => Promise<void> | void)[] = []
afterEach(async () => {
  for (const cleanup of cleanups.splice(0).reverse()) await cleanup()
})

/** The issuer, the Connector keys and the enrollments a farm server would hold. */
async function identities() {
  const issuer = await crypto.subtle.generateKey('Ed25519', true, [
    'sign',
    'verify',
  ])
  const policy = {
    issuer: 'https://farm.test',
    audience: 'connector-telemetry',
    ttlSeconds: 600,
    publicKeys: new Map([['k1', issuer.publicKey]]),
  }
  const enrollments = new Map<
    string,
    { status: string; publicKeySpki: string }
  >()
  async function connector(farmId: string, signingKey = issuer.privateKey) {
    const pair = await crypto.subtle.generateKey('Ed25519', true, [
      'sign',
      'verify',
    ])
    const publicKeySpki = Buffer.from(
      await crypto.subtle.exportKey('spki', pair.publicKey),
    ).toString('base64url')
    const agentId = randomUUID()
    enrollments.set(`${farmId}/${agentId}`, {
      status: 'approved',
      publicKeySpki,
    })
    const device_token = await issueConnectorCredential({
      ...policy,
      kid: 'k1',
      privateKey: signingKey,
      ttlSeconds: policy.ttlSeconds,
      agentId,
      farmId,
      publicKeySpki,
      nowSeconds: Math.floor(Date.now() / 1000),
      jti: randomUUID(),
    })
    const identity = new ConnectorIdentity(KeyObject.from(pair.privateKey))
    return { agent_id: agentId, farm_id: farmId, device_token, identity }
  }
  return {
    policy,
    connector,
    enrollments: {
      find: async (farmId: string, agentId: string) =>
        enrollments.get(`${farmId}/${agentId}`) ?? null,
    },
    revoke(farmId: string, agentId: string) {
      const record = enrollments.get(`${farmId}/${agentId}`)!
      enrollments.set(`${farmId}/${agentId}`, { ...record, status: 'revoked' })
    },
  }
}

/**
 * The server side as the Nitro plugin composes it (same function, in-memory
 * ports and a real blob directory), behind the same adapter the route uses.
 */
async function farmServer(
  options: {
    storageLocation?: LibraryBlobRecord['storageLocation']
    tamper?: boolean
  } = {},
) {
  const ids = await identities()
  const farm = randomUUID()
  const blobs = await createBlobStore(await directory('library-download-'))
  await blobs.put(Readable.from([gcode]))
  const audits: DownloadAuditEntry[] = []
  const reads: string[] = []
  const lifecycle = startConnectorLibraryDownload({
    credentials: ids.policy,
    enrollments: ids.enrollments,
    findBlob: async (farmId, sha256) =>
      farmId === farm && sha256 === hash
        ? {
            storageLocation: options.storageLocation ?? 'server',
            sizeBytes: gcode.length,
          }
        : null,
    audit: async (entry) => void audits.push(entry),
    blobs: {
      async read(sha256, range) {
        reads.push(sha256)
        const read = await blobs.read(sha256, range)
        if (!options.tamper) return read
        read.stream.destroy()
        const length = range ? range.end - range.start + 1 : read.size
        return {
          size: read.size,
          range,
          stream: Readable.from([Buffer.alloc(length, 0x41)]),
        }
      },
    },
  })
  const server: Server = createServer({ cert, key }, async (req, res) => {
    const handler = connectorLibraryDownload()
    const path = /^\/api\/connector\/library\/([^/]+)$/.exec(req.url ?? '')
    if (!path) {
      res.writeHead(404).end()
      return
    }
    if (!handler) {
      res.writeHead(503).end()
      return
    }
    const headers = new Headers()
    for (const [name, value] of Object.entries(req.headers))
      if (typeof value === 'string') headers.set(name, value)
    const answer = await handler(path[1]!, headers)
    res.writeHead(answer.status, answer.headers)
    if (answer.body instanceof Readable) answer.body.pipe(res)
    else res.end(JSON.stringify(answer.body))
  })
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve))
  cleanups.push(async () => {
    lifecycle.stop()
    await new Promise((resolve) => server.close(resolve))
  })
  const { port } = server.address() as AddressInfo
  return {
    ids,
    farm,
    audits,
    reads,
    endpoint: `https://localhost:${port}/api/connector/telemetry`,
    port,
  }
}

/** The real Connector composition, aimed at the server above. */
async function connectorFor(
  server: Awaited<ReturnType<typeof farmServer>>,
  credential: Awaited<
    ReturnType<Awaited<ReturnType<typeof identities>>['connector']>
  >,
) {
  const library = await createConnectorLibrary({
    endpoint: server.endpoint,
    credential,
    identity: credential.identity,
    dataDirectory: await directory('library-download-connector-'),
    ca: cert,
  })
  expect(library).toBeDefined()
  const mock = await startMoonrakerMock()
  cleanups.push(() => mock.close())
  const starter = library!.starterFor(async () => profile)
  const starts: string[] = []
  const start = () =>
    starter.start({
      args: { sha256: hash },
      target: { backend: 'moonraker', origin: mock.origin },
      signal,
      authorize: () => true,
      start: async (name) => void starts.push(name),
    })
  return { start, starts, mock }
}

function request(
  server: { port: number },
  credential: {
    agent_id: string
    farm_id: string
    device_token: string
    identity: ConnectorIdentity
  },
  extra: Record<string, string> = {},
) {
  return new Promise<{ status: number; headers: object; body: Buffer }>(
    (resolve, reject) => {
      get(
        `https://localhost:${server.port}/api/connector/library/${hash}`,
        {
          ca: cert,
          headers: {
            authorization: `Bearer ${credential.device_token}`,
            'x-connector-agent': credential.agent_id,
            'x-connector-farm': credential.farm_id,
            ...credential.identity.signLibraryProof({
              token: credential.device_token,
              agentId: credential.agent_id,
              farmId: credential.farm_id,
              now: Date.now(),
            }),
            ...extra,
          },
        },
        async (response) => {
          const parts: Buffer[] = []
          for await (const part of response) parts.push(Buffer.from(part))
          resolve({
            status: response.statusCode ?? 0,
            headers: response.headers,
            body: Buffer.concat(parts),
          })
        },
      ).on('error', reject)
    },
  )
}

describe('library download wiring', () => {
  test('is inactive until started and inactive again after stop', async () => {
    expect(connectorLibraryDownload()).toBeUndefined()
    await farmServer()
    expect(connectorLibraryDownload()).toBeDefined()
    for (const cleanup of cleanups.splice(0).reverse()) await cleanup()
    expect(connectorLibraryDownload()).toBeUndefined()
  })

  test('a paired Connector downloads a server-mode file, then resumes with a range', async () => {
    const server = await farmServer()
    const credential = await server.ids.connector(server.farm)
    const { start, starts, mock } = await connectorFor(server, credential)

    const first = await start()
    expect(first).toMatchObject({ ok: true, source: 'download' })
    const name = `${hash.slice(0, 16)}.gcode`
    expect(starts).toEqual([name])
    expect(mock.control.files.has(name)).toBe(true)

    // A broken transfer resumes from the byte it reached.
    const head = 37
    const resumed = await request(server, credential, {
      range: `bytes=${head}-`,
    })
    expect(resumed.status).toBe(206)
    expect(resumed.headers).toMatchObject({
      'content-range': `bytes ${head}-${gcode.length - 1}/${gcode.length}`,
    })
    expect(Buffer.concat([gcode.subarray(0, head), resumed.body])).toEqual(
      gcode,
    )

    expect(server.audits).toMatchObject([
      {
        farmId: server.farm,
        agentId: credential.agent_id,
        sha256: hash,
        outcome: 'served',
        range: null,
        bytes: gcode.length,
      },
      {
        outcome: 'served',
        range: { start: head, end: gcode.length - 1 },
        bytes: gcode.length - head,
      },
    ])
  })

  test('a second start of the same file uses the cache and downloads nothing', async () => {
    const server = await farmServer()
    const credential = await server.ids.connector(server.farm)
    const { start, starts } = await connectorFor(server, credential)
    expect(await start()).toMatchObject({ ok: true, source: 'download' })
    expect(await start()).toMatchObject({ ok: true, source: 'cache' })
    expect(starts).toHaveLength(2)
    expect(server.reads).toEqual([hash])
    expect(server.audits.map((entry) => entry.outcome)).toEqual(['served'])
  })

  test('a foreign-farm Connector is refused and gets no bytes', async () => {
    const server = await farmServer()
    const foreign = await server.ids.connector(randomUUID())
    const { start, starts, mock } = await connectorFor(server, foreign)
    expect(await start()).toMatchObject({
      ok: false,
      code: 'download-failed',
    })
    expect(starts).toEqual([])
    expect([...mock.control.files.keys()]).toEqual([])
    expect(server.reads).toEqual([])
    expect(server.audits).toMatchObject([
      { farmId: foreign.farm_id, outcome: 'not-found' },
    ])
  })

  test('a revoked Connector is refused at once, and so is a forged credential', async () => {
    const server = await farmServer()
    const credential = await server.ids.connector(server.farm)
    const { start } = await connectorFor(server, credential)
    server.ids.revoke(credential.farm_id, credential.agent_id)
    expect(await start()).toMatchObject({ ok: false, code: 'download-failed' })

    const other = await crypto.subtle.generateKey('Ed25519', true, [
      'sign',
      'verify',
    ])
    const forged = await server.ids.connector(server.farm, other.privateKey)
    expect((await request(server, forged)).status).toBe(403)
    expect(
      (
        await request(
          server,
          { ...credential, device_token: 'not.a.token' },
          {},
        )
      ).status,
    ).toBe(403)
    expect(server.reads).toEqual([])
    expect(server.audits).toEqual([])
  })

  test('a Connector-mode file is refused as kept on the Connector, with no bytes', async () => {
    const server = await farmServer({ storageLocation: 'connector' })
    const credential = await server.ids.connector(server.farm)
    const answer = await request(server, credential)
    expect(answer.status).toBe(409)
    expect(JSON.parse(answer.body.toString())).toEqual({
      error: 'O arquivo está guardado no Connector, não no servidor.',
    })
    const { start, starts } = await connectorFor(server, credential)
    expect(await start()).toMatchObject({ ok: false, code: 'download-failed' })
    expect(starts).toEqual([])
    expect(server.reads).toEqual([])
    expect(server.audits.map((entry) => entry.outcome)).toEqual([
      'kept-on-connector',
      'kept-on-connector',
    ])
  })

  test('a tampered blob is refused and never uploaded or started', async () => {
    const server = await farmServer({ tamper: true })
    const credential = await server.ids.connector(server.farm)
    const { start, starts, mock } = await connectorFor(server, credential)
    expect(await start()).toMatchObject({
      ok: false,
      code: 'checksum-mismatch',
    })
    expect(starts).toEqual([])
    expect([...mock.control.files.keys()]).toEqual([])
  })

  test('without an HTTPS server there is no library print', async () => {
    expect(
      await createConnectorLibrary({
        endpoint: 'http://localhost:1/api/connector/telemetry',
        credential: {
          device_token: 'a.b.c',
          farm_id: randomUUID(),
          agent_id: randomUUID(),
        },
        identity: new ConnectorIdentity(
          generateKeyPairSync('ed25519').privateKey,
        ),
        dataDirectory: await directory('library-download-connector-'),
      }),
    ).toBeUndefined()
  })
})

describe('printer profile for a library start', () => {
  const printer = (extra: Partial<PrinterState>) =>
    ({
      printerKey: 'p1',
      state: 'idle',
      ...extra,
    }) as PrinterState

  test('uses only what the printer reported and carries the machine block over', () => {
    const profiles = createPrinterProfiles()
    expect(profiles.read('p1')).toBeUndefined()
    profiles.observe(printer({ identity: { model: 'Printer One' } }))
    // A model alone is not a profile.
    expect(profiles.read('p1')).toBeUndefined()
    profiles.observe(
      printer({
        identity: { model: 'Printer One' },
        machine: {
          nozzleDiametersMm: [0.4],
          bedSizeMm: { x: 220, y: 220, z: 250 },
        },
      }),
    )
    // The machine block is sent on change only: the next report omits it.
    profiles.observe(printer({ identity: { model: 'Printer One' } }))
    expect(profiles.read('p1')).toEqual({
      model: 'Printer One',
      nozzleDiameters: [0.4],
      bedSize: { x: 220, y: 220, z: 250 },
    })
    expect(profiles.read('other')).toBeUndefined()
  })

  test('takes the nozzles of a printer that names no model, with an empty model', () => {
    const profiles = createPrinterProfiles()
    profiles.observe(printer({ machine: { nozzleDiametersMm: [0.4] } }))
    // Moonraker reports no model: a file that names one cannot match it.
    expect(profiles.read('p1')).toEqual({ model: '', nozzleDiameters: [0.4] })
  })
})
