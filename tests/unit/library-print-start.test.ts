/** Real directory under the worktree's ignored `.data/`; nothing else is touched. */
async function directory(prefix: string) {
  await mkdir(join(process.cwd(), '.data'), { recursive: true })
  return mkdtemp(join(process.cwd(), '.data', prefix))
}

/** In-process "server": serves blobs by hash and counts downloads. */
function server(blobs: Record<string, Buffer>) {
  const calls: string[] = []
  const download: LibraryDownloader = async (hash) => {
    calls.push(hash)
    const body = blobs[hash]
    if (!body) throw new Error('404')
    return {
      size: body.length,
      stream: (async function* () {
        yield body
      })(),
    }
  }
  return { download, calls }
}

async function setup(
  blobs: Record<string, Buffer>,
  over: Partial<Parameters<typeof createLibraryPrintStarter>[0]> = {},
  maxBytes = 1_000_000,
) {
  const { download, calls } = server(blobs)
  const cache = await createLibraryCache({
    directory: await directory('library-print-cache-'),
    maxBytes,
  })
  const starts: { name: string; extra: object }[] = []
  const starter = createLibraryPrintStarter({
    cache,
    download,
    profile: async () => profile,
    ...over,
  })
  const run = (
    target: FileUploadTarget,
    args: Parameters<typeof starter.start>[0]['args'],
  ): Promise<LibraryPrintResult> =>
    starter.start({
      args,
      target,
      signal,
      authorize: () => true,
      start: async (name, extra) => {
        starts.push({ name, extra })
      },
    })
  return { run, starts, calls, cache }
}

describe('start_library_print arguments and roles', () => {
  const sha256 = 'a'.repeat(64)
  test('fits the signed frame and rejects loose fields', () => {
    const ok = ControlArguments.safeParse({
      action: 'start_library_print',
      args: { sha256, plate: 2, ams_mapping: [0, -1, 3] },
    })
    expect(ok.success).toBe(true)
    expect(
      JSON.stringify({ action: 'start_library_print', args: ok.data?.args })
        .length,
    ).toBeLessThan(8 * 1024)
    for (const args of [
      { sha256: 'short' },
      { sha256, path: '/etc/passwd' },
      { sha256, plate: 0 },
      { sha256, ams_mapping: Array(65).fill(0) },
    ])
      expect(LibraryPrintArgs.safeParse(args).success).toBe(false)
  })
  test('API envelopes carry it under jobs:write only', () => {
    const action = { action: 'start_library_print', args: { sha256 } }
    expect(ApiEnvelopeAction.safeParse(action).success).toBe(true)
    expect(
      apiEnvelopeScope({ kind: 'action', action } as unknown as ApiEnvelopeV1),
    ).toBe('jobs:write')
    // start_print itself stays out of the API.
    expect(
      ApiEnvelopeAction.safeParse({
        action: 'start_print',
        args: { file: 'a.gcode' },
      }).success,
    ).toBe(false)
  })
  test('uses the start_print roles', () => {
    for (const role of ['owner', 'admin', 'operator', 'viewer'])
      expect(controlRoleAllowed(role, 'start_library_print')).toBe(
        controlRoleAllowed(role, 'start_print'),
      )
  })
})

describe('server mode (cache)', () => {
  test('Moonraker: downloads once, uploads and starts; second start reuses the cache', async () => {
    const body = gcode()
    const hash = sha(body)
    const mock = await startMoonrakerMock()
    try {
      const { run, starts, calls } = await setup({ [hash]: body })
      const target = { backend: 'moonraker', origin: mock.origin } as const
      const first = await run(target, { sha256: hash })
      expect(first).toMatchObject({ ok: true, source: 'download' })
      const second = await run(target, { sha256: hash })
      expect(second).toMatchObject({ ok: true, source: 'cache' })
      expect(calls).toEqual([hash])
      expect(starts).toHaveLength(2)
      const name = `${hash.slice(0, 16)}.gcode`
      expect(starts[0]).toEqual({ name, extra: {} })
      expect(mock.control.files.has(name)).toBe(true)
    } finally {
      await mock.close()
    }
  })

  test('Creality: uploads over the stock HTTP endpoint', async () => {
    const body = gcode()
    const hash = sha(body)
    const sim = await createCrealitySimulator()
    try {
      const { run, starts } = await setup({ [hash]: body })
      const result = await run(
        { backend: 'creality', origin: `http://127.0.0.1:${sim.httpPort}` },
        { sha256: hash },
      )
      expect(result.ok).toBe(true)
      const name = `${hash.slice(0, 16)}.gcode`
      // The simulator counts the multipart body, which wraps the file.
      expect(sim.uploads.get(name)).toBeGreaterThanOrEqual(body.length)
      expect(starts.map((s) => s.name)).toEqual([name])
    } finally {
      await sim.close()
    }
  })

  test('Bambu: carries plate and AMS mapping into the project_file command', async () => {
    const body = threeMf()
    const hash = sha(body)
    const uploads: string[] = []
    const { run, starts } = await setup(
      { [hash]: body },
      { upload: async (input) => void uploads.push(input.name) },
    )
    const bambu = { backend: 'bambu' } as unknown as FileUploadTarget
    const result = await run(bambu, {
      sha256: hash,
      plate: 2,
      ams_mapping: [1, -1],
    })
    expect(result).toMatchObject({ ok: true, name: `${hash.slice(0, 16)}.3mf` })
    expect(uploads).toEqual([`${hash.slice(0, 16)}.3mf`])
    const [only] = starts
    expect(only?.extra).toEqual({ plate: 2, ams_mapping: [1, -1] })
    expect(
      buildBambuCommand('start_print', { file: only!.name, ...only!.extra }),
    ).toMatchObject({
      print: {
        command: 'project_file',
        param: 'Metadata/plate_2.gcode',
        ams_mapping: [1, -1],
        use_ams: true,
      },
    })
    // A plate the project does not have is refused before anything is sent.
    const missing = await run(bambu, { sha256: hash, plate: 3 })
    expect(missing).toMatchObject({ ok: false, code: 'incompatible' })
    expect(starts).toHaveLength(1)
  })

  test('Anycubic: the target takes no file upload, so nothing is fetched or sent', async () => {
    const body = gcode()
    const hash = sha(body)
    const uploads: string[] = []
    const { run, starts } = await setup(
      { [hash]: body },
      { upload: async (input) => void uploads.push(input.name) },
    )
    const result = await run({ backend: 'anycubic' }, { sha256: hash })
    expect(result).toMatchObject({ ok: false, code: 'unsupported' })
    expect(uploads).toEqual([])
    expect(starts).toEqual([])
  })

  test('refuses an incompatible file on block and never uploads', async () => {
    const body = gcode('Another Printer')
    const hash = sha(body)
    const uploads: string[] = []
    const { run, starts } = await setup(
      { [hash]: body },
      { upload: async (input) => void uploads.push(input.name) },
    )
    const result = await run(
      { backend: 'moonraker', origin: 'http://127.0.0.1:1' },
      { sha256: hash },
    )
    expect(result).toMatchObject({
      ok: false,
      code: 'incompatible',
      reasons: ['O modelo de impressora indicado no arquivo é incompatível.'],
    })
    expect(uploads).toEqual([])
    expect(starts).toEqual([])
  })

  test('refuses a tampered blob', async () => {
    const hash = sha(gcode())
    const uploads: string[] = []
    const { run, starts } = await setup(
      { [hash]: gcode('Printer One\n; swapped') },
      { upload: async (input) => void uploads.push(input.name) },
    )
    const result = await run(
      { backend: 'moonraker', origin: 'http://127.0.0.1:1' },
      { sha256: hash },
    )
    expect(result).toMatchObject({ ok: false, code: 'checksum-mismatch' })
    expect(uploads).toEqual([])
    expect(starts).toEqual([])
  })

  test('maps download and cache failures to their result codes', async () => {
    const body = gcode()
    const hash = sha(body)
    const target = {
      backend: 'moonraker',
      origin: 'http://127.0.0.1:1',
    } as const
    expect(await (await setup({})).run(target, { sha256: hash })).toMatchObject(
      { ok: false, code: 'download-failed' },
    )
    expect(
      await (
        await setup({ [hash]: body }, {}, 10)
      ).run(target, {
        sha256: hash,
      }),
    ).toMatchObject({ ok: false, code: 'cache-full' })
  })

  test('plate and AMS mapping are Bambu-only; 3MF needs Bambu', async () => {
    const plain = gcode()
    const project = threeMf()
    const { run } = await setup({
      [sha(plain)]: plain,
      [sha(project)]: project,
    })
    const moonraker = {
      backend: 'moonraker',
      origin: 'http://127.0.0.1:1',
    } as const
    expect(
      await run(moonraker, { sha256: sha(plain), plate: 1 }),
    ).toMatchObject({ ok: false, code: 'incompatible' })
    expect(await run(moonraker, { sha256: sha(project) })).toMatchObject({
      ok: false,
      code: 'incompatible',
    })
  })

  test('an unauthorized start throws before the file is fetched', async () => {
    const hash = sha(gcode())
    const { download, calls } = server({ [hash]: gcode() })
    const starter = createLibraryPrintStarter({
      cache: await createLibraryCache({
        directory: await directory('library-print-cache-'),
        maxBytes: 1000,
      }),
      download,
      profile: async () => profile,
    })
    await expect(
      starter.start({
        args: { sha256: hash },
        target: { backend: 'moonraker', origin: 'http://127.0.0.1:1' },
        signal,
        authorize: () => false,
        start: async () => {},
      }),
    ).rejects.toThrow('unauthorized')
    expect(calls).toEqual([])
  })
})

describe('Connector mode (local library)', () => {
  async function local() {
    const store = await createLibraryStore({
      directory: await directory('library-print-local-'),
      freeBytes: async () => 1e12,
    })
    const body = gcode()
    const hash = sha(body)
    await store.put(
      (async function* () {
        yield body
      })(),
      {
        meta: {
          version_id: 'v1',
          item_id: 'i1',
          version_number: 1,
          name: 'benchy.gcode',
          kind: 'gcode',
        },
      },
    )
    return { store, body, hash }
  }
  const moonraker = { backend: 'moonraker', origin: '' } as const

  test('reads the local copy with no server download', async () => {
    const { store, hash } = await local()
    const mock = await startMoonrakerMock()
    try {
      const { run, starts, calls } = await setup({}, { local: store })
      const result = await run(
        { backend: 'moonraker', origin: mock.origin },
        { sha256: hash },
      )
      expect(result).toMatchObject({
        ok: true,
        source: 'local',
        name: 'benchy.gcode',
      })
      expect(calls).toEqual([])
      expect(starts.map((s) => s.name)).toEqual(['benchy.gcode'])
      expect(mock.control.files.has('benchy.gcode')).toBe(true)
    } finally {
      await mock.close()
    }
  })

  test('refuses an altered local file and never falls back to the server', async () => {
    const { store, hash } = await local()
    await writeFile(
      join((await store.openForPrint(hash)).path),
      gcode('Printer One\n; edited'),
    )
    const { run, starts, calls } = await setup(
      { [hash]: gcode() },
      { local: store },
    )
    expect(await run(moonraker, { sha256: hash })).toMatchObject({
      ok: false,
      code: 'checksum-mismatch',
    })
    expect(calls).toEqual([])
    expect(starts).toEqual([])
  })

  test('refuses a file the library no longer holds', async () => {
    const { store, hash } = await local()
    await store.purge([hash])
    const { run, starts, calls } = await setup(
      { [hash]: gcode() },
      { local: store },
    )
    expect(await run(moonraker, { sha256: hash })).toMatchObject({
      ok: false,
      code: 'local-file-missing',
    })
    expect(calls).toEqual([])
    expect(starts).toEqual([])
  })
})

describe('HTTPS library downloader', () => {
  test('sends the credential headers, keeps to the server and maps errors', async () => {
    const fixtures = join(process.cwd(), 'tests/fixtures/bambu-ftps')
    const cert = readFileSync(join(fixtures, 'cert.pem'))
    const body = gcode()
    const seen: Record<string, string | undefined>[] = []
    const https = createServer(
      { cert, key: readFileSync(join(fixtures, 'key.pem')) },
      (request, response) => {
        seen.push({
          url: request.url,
          authorization: request.headers.authorization,
        })
        if (request.url === `/api/connector/library/${sha(body)}`) {
          response.writeHead(200, { 'content-length': String(body.length) })
          response.end(body)
        } else {
          response.writeHead(302, { location: 'https://example.invalid/' })
          response.end()
        }
      },
    )
    await new Promise<void>((resolve) => https.listen(0, '127.0.0.1', resolve))
    try {
      const { port } = https.address() as AddressInfo
      const download = createHttpsLibraryDownloader({
        baseUrl: `https://localhost:${port}`,
        headers: () => ({ authorization: 'Bearer proof' }),
        ca: cert,
      })
      const cache = await createLibraryCache({
        directory: await directory('library-print-cache-'),
        maxBytes: 1_000_000,
      })
      const file = await cache.acquire(sha(body), download, signal)
      expect(file.size).toBe(body.length)
      file.release()
      expect(seen[0]).toEqual({
        url: `/api/connector/library/${sha(body)}`,
        authorization: 'Bearer proof',
      })
      // A redirect is a failure: credentials never follow it elsewhere.
      await expect(download(sha('other'), signal)).rejects.toThrow(
        'download-failed',
      )
      expect(() =>
        createHttpsLibraryDownloader({
          baseUrl: 'http://localhost',
          headers: () => ({}),
        }),
      ).toThrow()
    } finally {
      await new Promise((resolve) => https.close(resolve))
    }
  })
})
