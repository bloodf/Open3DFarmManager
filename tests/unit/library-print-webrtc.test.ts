async function until<T>(read: () => T | undefined | false, ms = 8000) {
  const end = Date.now() + ms
  for (;;) {
    const value = read()
    if (value) return value
    if (Date.now() > end) throw new Error('Timed out')
    await sleep(10)
  }
}

/** Every journalled command's status, oldest first. */
function journalStatuses(path: string) {
  const database = new DatabaseSync(join(path, 'pause-commands.sqlite'), {
    readOnly: true,
  })
  try {
    return database
      .prepare('SELECT status FROM pause_commands ORDER BY claimed_at')
      .all()
      .map((row) => row.status)
  } finally {
    database.close()
  }
}

