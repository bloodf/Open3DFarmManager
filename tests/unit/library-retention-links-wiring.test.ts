async function directory(prefix: string) {
  await mkdir(join(process.cwd(), '.data'), { recursive: true })
  const path = await mkdtemp(join(process.cwd(), '.data', prefix))
  cleanups.push(() => rm(path, { recursive: true, force: true }))
  return path
}
const stored = async (dir: string) =>
  (await readdir(dir).catch(() => [])).filter((name) =>
    /^[0-9a-f]{64}$/.test(name),
  )

type Plugin = (nitro: {
  hooks: { hook(name: string, listener: () => Promise<void>): void }
}) => void

// Nitro's auto-imported global, as far as the two plugins under test use it.
declare global {
  function defineNitroPlugin(plugin: Plugin): Plugin
}

/** Runs a Nitro plugin the way Nitro does and returns its `close` hook. */
function startPlugin(plugin: Plugin) {
  let close: (() => Promise<void>) | undefined
  plugin({
    hooks: {
      hook(name, listener) {
        if (name === 'close') close = listener
      },
    },
  })
  cleanups.push(async () => close?.())
}

async function world() {
  const issuer = await crypto.subtle.generateKey('Ed25519', true, [
    'sign',
    'verify',
  ])
  const pair = await crypto.subtle.generateKey('Ed25519', true, [
    'sign',
    'verify',
  ])
  const publicKeySpki = Buffer.from(
    await crypto.subtle.exportKey('spki', pair.publicKey),
  ).toString('base64url')
  const farmId = randomUUID()
  const agentId = randomUUID()
  h.keys = new Map([['k1', issuer.publicKey]])
  const device_token = await issueConnectorCredential({
    issuer: 'https://farm.test',
    audience: 'connector-telemetry',
    ttlSeconds: 600,
    kid: 'k1',
    privateKey: issuer.privateKey,
    agentId,
    farmId,
    publicKeySpki,
    nowSeconds: Math.floor(Date.now() / 1000),
    jti: randomUUID(),
  })
  const db = fakeDatabase({ farmId, agentId, publicKeySpki })
  h.sql = db.sql
  h.config = {
    library: {
      enabled: true,
      databaseUrl: 'postgres://farm_library:secret@127.0.0.1:1/farm',
    },
    connectorTelemetry: {
      enabled: true,
      databaseUrl: 'postgres://telemetry:secret@127.0.0.1:1/farm',
      origin: 'https://farm.test',
      issuer: 'https://farm.test',
      audience: 'connector-telemetry',
      publicKeyRegistryPath: '/keys.json',
      tokenTtlSeconds: 600,
      proofTtlMs: 5000,
      bodyTimeoutMs: 5000,
    },
    libraryRetention: {
      enabled: true,
      databaseUrl: 'postgres://farm_library_retention:secret@127.0.0.1:1/farm',
      intervalMs: 3_600_000,
      batchSize: 50,
    },
  }
  vi.stubGlobal('defineNitroPlugin', (plugin: Plugin) => plugin)

  // The relay lifecycle plugin starts the relay hub with the storage recorder.
  const { default: relayPlugin } =
    await import('../../apps/farm/server/plugins/library-relay-lifecycle.ts')
  startPlugin(relayPlugin as unknown as Plugin)
  await until(
    () => activeConnectorLibraryRelay() !== undefined,
    'the relay to start',
  )

  // The Nitro route files, behind a plain HTTPS adapter on 127.0.0.1:0.
  const server: Server = createServer({ cert, key }, async (req, res) => {
    const url = new URL(req.url ?? '/', 'https://127.0.0.1')
    const headers = new Headers()
    for (const [name, value] of Object.entries(req.headers))
      if (typeof value === 'string') headers.set(name, value)
    const request = new Request(url, {
      method: req.method ?? 'GET',
      headers,
      ...(req.method === 'GET'
        ? {}
        : { body: Readable.toWeb(req) as ReadableStream, duplex: 'half' }),
    } as RequestInit)
    const op =
      /^\/api\/connector\/library\/relay\/([^/]+)\/(body|result)$/.exec(
        url.pathname,
      )
    const event = { req: request, context: { params: { opId: op?.[1] } } }
    const handler =
      url.pathname === '/api/connector/library/relay/poll'
        ? pollRoute
        : url.pathname === '/api/connector/library/relay/storage'
          ? storageRoute
          : op?.[2] === 'body'
            ? bodyRoute
            : op?.[2] === 'result'
              ? resultRoute
              : undefined
    const response = handler
      ? ((await (handler as unknown as (e: unknown) => unknown)(
          event,
        )) as Response)
      : new Response(null, { status: 404 })
    res.writeHead(response.status, Object.fromEntries(response.headers))
    if (response.body) Readable.fromWeb(response.body as never).pipe(res)
    else res.end()
  })
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve))
  cleanups.push(async () => {
    server.closeAllConnections()
    await new Promise((resolve) => server.close(resolve))
  })
  const port = (server.address() as AddressInfo).port

  // The Connector, composed from configuration the way the agent composes it.
  const dataDirectory = await directory('library-retention-links-')
  const hostLibrary = join(dataDirectory, 'host-library')
  const controller = new AbortController()
  const library = await createConnectorLibrary({
    endpoint: `https://localhost:${port}/api/connector/telemetry`,
    credential: { device_token, farm_id: farmId, agent_id: agentId },
    dataDirectory,
    ca: cert,
    library: { directory: hostLibrary, quotaBytes: 5_000_000 },
  })
  expect(library).toBeDefined()
  const diagnostics: string[] = []
  const serving = library!.serveRelay(controller.signal, (event) =>
    diagnostics.push(event.reason),
  )
  cleanups.push(async () => {
    controller.abort()
    await serving
  })

  /** An upload as the route runs it: the bytes go through the relay to the host. */
  async function upload(data: Buffer, createdAt = Date.now()) {
    const put = await connectorLibraryRelay.put({
      farmId,
      agentId,
      body: Readable.from([data]),
      maxBytes: 512 * 1024 * 1024,
    })
    expect(put.sha256).toBe(sha(data))
    db.state.blobs.push({
      farmId,
      sha256: put.sha256,
      sizeBytes: put.size,
      agentId,
      createdAt,
      purgedAt: null,
    })
    return put.sha256
  }
  const reported = () => db.state.storage.find((row) => row.agentId === agentId)

  return {
    farmId,
    agentId,
    db,
    library: library!,
    hostLibrary,
    upload,
    reported,
    diagnostics,
    dataDirectory,
    /** A raw call to the storage route, with or without the Connector's credential. */
    post(body: unknown, authenticated: boolean) {
      return new Promise<number>((resolve, reject) => {
        const payload = Buffer.from(JSON.stringify(body))
        const req = request(
          `https://localhost:${port}/api/connector/library/relay/storage`,
          {
            method: 'POST',
            ca: cert,
            headers: {
              'content-length': String(payload.length),
              ...(authenticated
                ? {
                    authorization: `Bearer ${device_token}`,
                    'x-connector-agent': agentId,
                    'x-connector-farm': farmId,
                  }
                : {}),
            },
          },
          (res) => {
            res.resume()
            res.once('close', () => resolve(res.statusCode ?? 0))
          },
        )
        req.on('error', reject)
        req.end(payload)
      })
    },
  }
}

describe(
  'Connector library retention, quota reports and job links, composed',
  { timeout: 60_000 },
  () => {
    test('a file past retention is deleted on the Connector, its row purged and the farm quota follows', async () => {
      const w = await world()
      const kept = gcode('kept')
      const old = gcode('old')
      const keptSha = await w.upload(kept)
      const oldSha = await w.upload(old, Date.now() - 40 * DAY)
      expect((await stored(w.hostLibrary)).sort()).toEqual(
        [keptSha, oldSha].sort(),
      )
      // The Connector reports its own usage; the farm stores it as the quota basis.
      await until(
        () => w.reported()?.usedBytes === kept.length + old.length,
        'the storage report for two files',
      )
      expect(w.reported()).toMatchObject({ quotaBytes: 5_000_000 })

      // Both versions were deleted; only one for longer than the 30-day window.
      w.db.state.versions.push(
        { farmId: w.farmId, sha256: keptSha, deletedAt: Date.now() - DAY },
        { farmId: w.farmId, sha256: oldSha, deletedAt: Date.now() - 31 * DAY },
      )
      const { default: retentionPlugin } =
        await import('../../apps/farm/server/plugins/library-retention.ts')
      startPlugin(retentionPlugin as unknown as Plugin)

      await until(
        () =>
          w.db.state.blobs.find((b) => b.sha256 === oldSha)!.purgedAt !== null,
        'the retention purge',
      )
      // The file is gone from the Connector host; the one inside the window stays.
      expect(await stored(w.hostLibrary)).toEqual([keptSha])
      expect(
        w.db.state.blobs.find((b) => b.sha256 === keptSha)!.purgedAt,
      ).toBeNull()
      // The purge changed the host's usage and the Connector said so.
      await until(
        () => w.reported()?.usedBytes === kept.length,
        'the storage report after the purge',
      )
      const usage = summarizeUsage(
        'connector',
        { usedBytes: 0, quotaBytes: 0 },
        await connectorReports(w.db.sql, w.farmId),
      )
      expect(usage).toMatchObject({
        usedBytes: kept.length,
        quotaBytes: 5_000_000,
        unreported: false,
      })
      expect(describeUsage(usage)).toContain('livres')
      expect(w.diagnostics).toEqual([])
    })

    test('the storage route stores a valid report and refuses a missing credential or a malformed body', async () => {
      const w = await world()
      const report = {
        type: 'library.storage.report',
        quota_bytes: 9_000_000,
        used_bytes: 1234,
        retention_days: 30,
        keep_versions: null,
        reported_at: Date.now(),
      }
      // The Connector's own first report lands first, so the one below is the latest.
      await until(() => w.reported() !== undefined, 'the first report')
      expect(await w.post(report, false)).toBe(403)
      expect(await w.post({ ...report, used_bytes: -1 }, true)).toBe(400)
      expect(await w.post({ ...report, extra: 1 }, true)).toBe(400)
      expect(await w.post(report, true)).toBe(204)
      await until(
        () => w.reported()?.quotaBytes === 9_000_000,
        'the stored report',
      )
      expect(w.reported()).toMatchObject({ usedBytes: 1234 })
    })

    test('a job started from the library and finished reports its version, and the server returns it', async () => {
      const w = await world()
      const file = gcode('job')
      const hash = await w.upload(file)
      // The listed version, as the Connector's index holds it for a library start.
      await w.library.store.link(hash, {
        version_id: 'version-1',
        item_id: 'item-1',
        version_number: 1,
        name: 'job.gcode',
        kind: 'gcode',
      })
      const mock = await startMoonrakerMock()
      cleanups.push(() => mock.close())
      const queue = new TelemetryQueue(
        join(await directory('library-links-queue-'), 'queue'),
        Date.now(),
      )
      cleanups.push(() => queue.close())
      const links = createLibraryJobLinks()
      const collecting = new AbortController()
      const collected = collectIntoQueue({
        config: {
          version: 1,
          allowedOrigins: [mock.origin],
          printers: [{ printerKey, origin: mock.origin }],
          limits: {
            maxMessageBytes: 65_536,
            connectTimeoutMs: 1000,
            requestTimeoutMs: 1000,
            staleAfterMs: 30_000,
            reconnectMinMs: 100,
            reconnectMaxMs: 200,
          },
        },
        libraryLinks: links,
        queue,
        signal: collecting.signal,
        onDiagnostic() {},
      })
      cleanups.push(async () => {
        collecting.abort()
        await collected
      })
      const events: unknown[] = []
      const drain = () => {
        for (;;) {
          const { records } = queue.batch(Date.now())
          if (!records.length) break
          queue.acknowledge(
            records.map((record) => record.eventId),
            Date.now(),
          )
          events.push(...records)
        }
        return events as Parameters<typeof jobsFromEvents>[0]
      }
      await until(() => drain().length > 0, 'the first printer state')

      // The library start, from the Connector's own store, as the command runs it.
      const starter = w.library.starterFor(async () => ({
        model: 'Printer One',
        nozzleDiameters: [0.4],
      }))
      const outcome = await starter.start({
        args: { sha256: hash },
        target: { backend: 'moonraker', origin: mock.origin },
        signal: new AbortController().signal,
        authorize: () => true,
        start: async (name) => {
          const response = await fetch(
            `${mock.origin}/printer/print/start?filename=${encodeURIComponent(name)}`,
            { method: 'POST' },
          )
          expect(response.ok).toBe(true)
        },
      })
      expect(outcome).toMatchObject({ ok: true })
      if (!outcome.ok) return
      links.remember(printerKey, { name: outcome.name, sha256: hash })

      // The printer reports the run, then finishes it.
      await until(() => {
        drain()
        return events.some(
          (event) =>
            (event as { state?: PrinterState }).state?.state === 'printing',
        )
      }, 'the printing state')
      mock.control.update({ progress: 0.5 })
      await new Promise((resolve) => setTimeout(resolve, 100))
      mock.control.completePrint()
      await until(
        () => jobsFromEvents(drain()).some((job) => job.endedAt > 0),
        'the finished job',
      )

      const jobs = jobsFromEvents(drain())
      expect(jobs).toHaveLength(1)
      expect(jobs[0]).toMatchObject({
        printerKey,
        outcome: 'completed',
        librarySha256: hash,
      })
      expect(jobs[0]).not.toHaveProperty('plate')
      // Stored by the telemetry writer, returned by the history read.
      const scope = { farmId: w.farmId, agentId: w.agentId }
      await recordJobs(w.db.sql as never, scope, jobs)
      const history = await new PostgresJobHistory(w.db.sql).list({
        sessionRecordId: 'session',
        policy: { idleTimeoutMs: DAY },
        farmId: w.farmId,
        printerKey,
        limit: 10,
        before: null,
      })
      expect(history).toMatchObject({
        ok: true,
        jobs: [{ printerKey, outcome: 'completed', librarySha256: hash }],
      })
    })
  },
)
