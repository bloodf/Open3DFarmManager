async function until(check: () => boolean | Promise<boolean>, what: string) {
  const deadline = Date.now() + 15_000
  while (!(await check())) {
    if (Date.now() > deadline) throw new Error(`Timed out waiting for ${what}`)
    await new Promise((resolve) => setTimeout(resolve, 20))
  }
}

// ---- an in-process stand-in for the statements the server issues -----------

interface Blob {
  farmId: string
  sha256: string
  sizeBytes: number
  agentId: string
  createdAt: number
  purgedAt: number | null
}
interface Version {
  farmId: string
  sha256: string
  deletedAt: number | null
}
interface StorageRow {
  agentId: string
  quotaBytes: number
  usedBytes: number
  reportedAt: number
}
type JobRow = Record<string, unknown>

function fakeDatabase(identity: {
  farmId: string
  agentId: string
  publicKeySpki: string
}) {
  const state = {
    blobs: [] as Blob[],
    versions: [] as Version[],
    storage: [] as StorageRow[],
    jobs: [] as JobRow[],
  }
  const factsFor = (blob: Blob) => {
    const refs = state.versions.filter(
      (v) => v.farmId === blob.farmId && v.sha256 === blob.sha256,
    )
    const deleted = refs.map((v) => v.deletedAt).filter((d) => d !== null)
    return {
      farmId: blob.farmId,
      sha256: blob.sha256,
      sizeBytes: blob.sizeBytes,
      location: 'connector' as const,
      agentId: blob.agentId,
      createdAt: blob.createdAt,
      retentionDays: 30,
      refs: refs.length,
      live: refs.some((v) => v.deletedAt === null),
      newestDeletedAt: deleted.length ? Math.max(...deleted) : null,
    }
  }
  const run = async (strings: TemplateStringsArray, ...values: unknown[]) => {
    const text = strings.join('?').replace(/\s+/g, ' ').trim()
    // Fragments composed into a larger statement.
    if (text.startsWith('SELECT b.farm_id') || text.startsWith('GROUP BY'))
      return []
    if (text.startsWith('SET LOCAL') || text.includes('pg_advisory_xact_lock'))
      return []
    // Connector enrollment: the credential check and the storage report guard.
    if (text.includes('public_key_spki')) {
      const [farmId, agentId] = values
      return farmId === identity.farmId && agentId === identity.agentId
        ? [{ status: 'approved', publicKeySpki: identity.publicKeySpki }]
        : []
    }
    if (text.includes('FROM farm.connector_enrollments')) return [{}]
    if (text.startsWith('INSERT INTO farm.library_connector_storage')) {
      const [, agentId, quotaBytes, usedBytes, reportedAt] = values as [
        string,
        string,
        number,
        number,
        number,
      ]
      state.storage = [
        ...state.storage.filter((row) => row.agentId !== agentId),
        { agentId, quotaBytes, usedBytes, reportedAt },
      ]
      return []
    }
    if (text.includes('FROM farm.library_connector_storage'))
      return [...state.storage]
    // Retention.
    if (text.startsWith('UPDATE farm.library_versions')) return []
    if (text.includes('HAVING'))
      return state.blobs.filter((b) => b.purgedAt === null).map(factsFor)
    if (text.includes('b.sha256=')) {
      const [, farmId, sha256] = values as [unknown, string, string]
      return state.blobs
        .filter(
          (b) =>
            b.farmId === farmId && b.sha256 === sha256 && b.purgedAt === null,
        )
        .map(factsFor)
    }
    if (text.startsWith('UPDATE farm.library_blobs SET purged_at')) {
      const [now, farmId, sha256] = values as [number, string, string]
      const blob = state.blobs.find(
        (b) =>
          b.farmId === farmId && b.sha256 === sha256 && b.purgedAt === null,
      )
      if (!blob) return []
      blob.purgedAt = now
      return [{ one: 1 }]
    }
    if (text.startsWith('SELECT DISTINCT agent_id'))
      return [...new Set(state.blobs.map((b) => b.agentId))].map((agentId) => ({
        agentId,
      }))
    if (
      text.startsWith('SELECT sha256 FROM farm.library_blobs WHERE agent_id=')
    )
      return state.blobs
        .filter((b) => b.purgedAt === null)
        .map((b) => ({ sha256: b.sha256 }))
    // Job history: the telemetry insert and the owner's list.
    if (text.startsWith('INSERT INTO farm.job_history')) {
      const [, , printer, outcome, filename, , , , librarySha256, plate, end] =
        values
      state.jobs.push({
        id: String(state.jobs.length + 1),
        printerKey: printer,
        outcome,
        filename,
        printDurationSeconds: null,
        totalDurationSeconds: null,
        filamentUsage: null,
        librarySha256,
        plate,
        endedAt: end,
      })
      return []
    }
    if (text.includes('session_version'))
      return [{ id: 'owner', sessionVersion: 1, disabled: false }]
    if (text.includes('account_id AS "accountId"'))
      return [
        {
          id: 'session',
          accountId: 'owner',
          accountVersion: 1,
          createdAt: 1,
          lastSeenAt: Date.now() - 1000,
          absoluteExpiresAt: Date.now() + DAY,
          revokedAt: null,
        },
      ]
    if (text.includes('FROM farm.memberships'))
      return [{ role: 'owner', revoked_at: null }]
    if (text.includes('FROM farm.job_history')) return [...state.jobs]
    if (text.startsWith('UPDATE farm.account_sessions')) return []
    throw new Error(`Unexpected statement: ${text.slice(0, 80)}`)
  }
  const sql = Object.assign(run, {
    // A failed transaction leaves nothing behind.
    async begin(work: (tx: unknown) => Promise<unknown>) {
      const before = structuredClone(state)
      try {
        return await work(sql)
      } catch (error) {
        Object.assign(state, before)
        throw error
      }
    },
    async end() {},
  }) as unknown as Sql
  return { state, sql }
}

