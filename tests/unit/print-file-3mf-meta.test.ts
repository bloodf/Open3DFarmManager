import { describe, expect, it } from 'vitest'
import { crc32, deflateRawSync } from 'node:zlib'
import {
  readThreeMf,
  UNSLICED_REASON,
  type ThreeMfResult,
} from '../../packages/shared/src/print-file/3mf-meta.ts'

/** Minimal in-memory ZIP writer for generated .3mf fixtures. */
function buildZip(files: Record<string, Buffer | string>): Buffer {
  const parts: Buffer[] = []
  const central: Buffer[] = []
  let offset = 0
  for (const [path, content] of Object.entries(files)) {
    const data = Buffer.from(content)
    const body = deflateRawSync(data)
    const name = Buffer.from(path)
    const local = Buffer.alloc(30)
    local.writeUInt32LE(0x04034b50, 0)
    local.writeUInt16LE(20, 4)
    local.writeUInt16LE(8, 8)
    local.writeUInt32LE(crc32(data), 14)
    local.writeUInt32LE(body.length, 18)
    local.writeUInt32LE(data.length, 22)
    local.writeUInt16LE(name.length, 26)
    const header = Buffer.alloc(46)
    header.writeUInt32LE(0x02014b50, 0)
    header.writeUInt16LE(20, 4)
    header.writeUInt16LE(20, 6)
    header.writeUInt16LE(8, 10)
    header.writeUInt32LE(crc32(data), 16)
    header.writeUInt32LE(body.length, 20)
    header.writeUInt32LE(data.length, 24)
    header.writeUInt16LE(name.length, 28)
    header.writeUInt32LE(offset, 42)
    central.push(header, name)
    parts.push(local, name, body)
    offset += 30 + name.length + body.length
  }
  const directory = Buffer.concat(central)
  const count = Object.keys(files).length
  const eocd = Buffer.alloc(22)
  eocd.writeUInt32LE(0x06054b50, 0)
  eocd.writeUInt16LE(count, 8)
  eocd.writeUInt16LE(count, 10)
  eocd.writeUInt32LE(directory.length, 12)
  eocd.writeUInt32LE(offset, 16)
  return Buffer.concat([...parts, directory, eocd])
}

const PNG = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  Buffer.from('fake-plate-image'),
])

function sliceInfo(plates: number): string {
  const body = Array.from({ length: plates }, (_, i) => {
    const n = i + 1
    return `  <plate>
    <metadata key="index" value="${n}"/>
    <metadata key="printer_model_id" value="C11"/>
    <metadata key="nozzle_diameters" value="0.4"/>
    <metadata key="prediction" value="${600 * n}"/>
    <metadata key="weight" value="${n}.5"/>
    <object identify_id="${n}0" name="Cubo &amp; Tampa ${n}" skipped="${n === 2}"/>
    <filament id="1" tray_info_idx="GFA00" type="PLA" color="#FF0000" used_m="${n}.25" used_g="${n}.75"/>
    <filament id="2" type="PETG" color="#00FF00" used_m="0.5" used_g="1.5"/>
  </plate>`
  }).join('\n')
  return `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header>
    <header_item key="X-BBL-Client-Type" value="slicer"/>
    <header_item key="X-BBL-Client-Version" value="01.10.00.00"/>
  </header>
${body}
</config>`
}

const settings = JSON.stringify({
  printer_model: 'Bambu Lab X1 Carbon',
  printer_settings_id: 'Bambu Lab X1 Carbon 0.4 nozzle',
  nozzle_diameter: ['0.4'],
  filament_type: ['PLA', 'PETG', 'ABS'],
  filament_colour: ['#FF0000', '#00FF00', '#0000FF'],
})

function gcode(n: number, filler = 0): string {
  const middle = Array.from(
    { length: filler },
    (_, i) => `G1 X${(i * 7) % 251}.${i % 97} Y${(i * 13) % 241}.${i % 89}\n`,
  ).join('')
  return `; generated by BambuStudio 01.10.00.00\n; layer_height = 0.2\n; printer_model = Bambu Lab X1 Carbon\n${middle}; total_layer_count = ${n * 10}\n`
}

function project(
  plates: number,
  extra: Record<string, Buffer | string> = {},
  sliced = true,
): Buffer {
  const files: Record<string, Buffer | string> = {
    '[Content_Types].xml': '<Types/>',
    '3D/3dmodel.model': '<model/>',
    'Metadata/project_settings.config': settings,
  }
  if (sliced) files['Metadata/slice_info.config'] = sliceInfo(plates)
  for (let n = 1; n <= plates; n++) {
    if (sliced) files[`Metadata/plate_${n}.gcode`] = gcode(n)
    files[`Metadata/plate_${n}.png`] = PNG
  }
  return buildZip({ ...files, ...extra })
}

function okProject(result: ThreeMfResult) {
  if (!result.ok) throw new Error(`refused: ${result.code} ${result.reason}`)
  return result.project
}

describe('3MF project reader', () => {
  it('reads a sliced one-plate project', async () => {
    const result = okProject(await readThreeMf(project(1)))
    expect(result).toMatchObject({
      sliced: true,
      startable: true,
      slicer: 'Bambu Studio',
      slicerVersion: '01.10.00.00',
      printerModel: 'Bambu Lab X1 Carbon',
      printerProfile: 'Bambu Lab X1 Carbon 0.4 nozzle',
      nozzleDiameter: 0.4,
    })
    expect(result.unstartableReason).toBeUndefined()
    expect(result.filaments).toEqual([
      { id: 1, type: 'PLA', colour: '#FF0000' },
      { id: 2, type: 'PETG', colour: '#00FF00' },
      { id: 3, type: 'ABS', colour: '#0000FF' },
    ])
    expect(result.plates).toHaveLength(1)
    const [plate] = result.plates
    expect(plate).toMatchObject({
      index: 1,
      startable: true,
      gcodePath: 'Metadata/plate_1.gcode',
      estimatedTimeSeconds: 600,
      weightGrams: 1.5,
      nozzleDiameter: 0.4,
      printerModelId: 'C11',
      thumbnail: { mimeType: 'image/png', data: PNG.toString('base64') },
      gcode: {
        slicer: 'Bambu Studio',
        layerHeight: 0.2,
        totalLayers: 10,
        printerModel: 'Bambu Lab X1 Carbon',
      },
    })
    expect(plate?.objects).toEqual([{ name: 'Cubo & Tampa 1', skipped: false }])
    expect(plate?.filaments).toEqual([
      {
        id: 1,
        type: 'PLA',
        colour: '#FF0000',
        usedMeters: 1.25,
        usedGrams: 1.75,
      },
      {
        id: 2,
        type: 'PETG',
        colour: '#00FF00',
        usedMeters: 0.5,
        usedGrams: 1.5,
      },
    ])
  })

  it('reads a sliced three-plate project with per-plate data', async () => {
    const result = okProject(await readThreeMf(project(3)))
    expect(result.plates.map((plate) => plate.index)).toEqual([1, 2, 3])
    expect(result.plates.map((plate) => plate.estimatedTimeSeconds)).toEqual([
      600, 1200, 1800,
    ])
    expect(result.plates.map((plate) => plate.gcode?.totalLayers)).toEqual([
      10, 20, 30,
    ])
    expect(
      result.plates.every(
        (plate) => plate.startable && plate.thumbnail?.mimeType === 'image/png',
      ),
    ).toBe(true)
    expect(result.plates[1]?.objects).toEqual([
      { name: 'Cubo & Tampa 2', skipped: true },
    ])
    expect(result.plates[2]?.filaments[0]).toMatchObject({
      usedMeters: 3.25,
      usedGrams: 3.75,
    })
  })

  it('parses the footer of a plate G-code far larger than the header window', async () => {
    const big = buildZip({
      '3D/3dmodel.model': '<model/>',
      'Metadata/slice_info.config': sliceInfo(1),
      'Metadata/plate_1.gcode': gcode(7, 250_000),
    })
    const plate = okProject(await readThreeMf(big)).plates[0]
    expect(plate?.gcode).toMatchObject({
      slicer: 'Bambu Studio',
      totalLayers: 70,
    })
  })

  it('reports an unsliced project as such and refuses to start it', async () => {
    const result = okProject(await readThreeMf(project(1, {}, false)))
    expect(result).toMatchObject({
      sliced: false,
      startable: false,
      unstartableReason: UNSLICED_REASON,
      printerModel: 'Bambu Lab X1 Carbon',
    })
    expect(result.plates.every((plate) => !plate.startable)).toBe(true)
    expect(result.plates.every((plate) => plate.gcodePath === undefined)).toBe(
      true,
    )
    const bare = okProject(
      await readThreeMf(buildZip({ '3D/3dmodel.model': '<model/>' })),
    )
    expect(bare).toMatchObject({
      sliced: false,
      startable: false,
      plates: [],
      filaments: [],
    })
  })

  it('marks only plates with G-code as startable in a partly sliced project', async () => {
    const files = buildZip({
      '3D/3dmodel.model': '<model/>',
      'Metadata/slice_info.config': sliceInfo(2),
      'Metadata/plate_2.gcode': gcode(2),
    })
    const result = okProject(await readThreeMf(files))
    expect(result.plates.map((plate) => plate.startable)).toEqual([false, true])
    expect(result.startable).toBe(true)
  })

  it('tolerates malformed settings and ignores thumbnails that are not PNG', async () => {
    const result = okProject(
      await readThreeMf(
        project(1, {
          'Metadata/project_settings.config': '{not json',
          'Metadata/plate_1.png': 'plain text',
        }),
      ),
    )
    expect(result.printerModel).toBeUndefined()
    expect(result.plates[0]?.thumbnail).toBeUndefined()
    expect(result.plates[0]?.startable).toBe(true)
  })

  it('refuses files that are not a 3MF project, with a reason', async () => {
    const notZip = await readThreeMf(
      Buffer.from('definitely not a zip archive'),
    )
    expect(notZip).toMatchObject({ ok: false, code: 'not-zip' })
    const noModel = await readThreeMf(
      buildZip({ 'Metadata/slice_info.config': sliceInfo(1) }),
    )
    expect(noModel).toMatchObject({ ok: false, code: 'not-3mf' })
    expect(noModel.ok ? '' : noModel.reason).toContain('3dmodel.model')
  })

  it('refuses a zip bomb, path traversal and duplicate entries inside a 3MF', async () => {
    const bomb = await readThreeMf(
      project(1, { 'Metadata/bomb.bin': Buffer.alloc(64 * 1024 * 1024) }),
    )
    expect(bomb).toMatchObject({ ok: false, code: 'zip-bomb' })
    const traversal = await readThreeMf(project(1, { '../../etc/passwd': 'x' }))
    expect(traversal).toMatchObject({ ok: false, code: 'path-traversal' })
    const duplicated = buildZip({
      '3D/3dmodel.model': '<model/>',
      'Metadata/a.txt': 'x',
      'metadata/A.TXT': 'y',
    })
    expect(await readThreeMf(duplicated)).toMatchObject({
      ok: false,
      code: 'duplicate-entry',
    })
    for (const result of [bomb, traversal])
      expect(result.ok ? '' : result.reason.length).toBeGreaterThan(10)
  })

  it('applies caller limits to the project', async () => {
    expect(await readThreeMf(project(3), { maxEntries: 4 })).toMatchObject({
      ok: false,
      code: 'too-many-entries',
    })
    expect(await readThreeMf(project(1), { maxTotalBytes: 20 })).toMatchObject({
      ok: false,
      code: 'total-too-large',
    })
  })
})
