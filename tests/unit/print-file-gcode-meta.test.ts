import { describe, expect, it } from 'vitest'
import { open, mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { parseGcodeMetadata, parseGcodeMetadataText } from '../../packages/shared/src/print-file/gcode-meta.ts'
import { PrintFileMetadata } from '../../packages/shared/src/print-file/metadata.ts'

const dialects = ['PrusaSlicer', 'SuperSlicer', 'OrcaSlicer', 'Bambu Studio', 'Creality Print', 'Anycubic Slicer Next', 'Cura_SteamEngine']
describe('G-code metadata', () => {
  it.each(dialects)('parses a synthetic %s header', slicer => {
    const metadata = parseGcodeMetadataText(`; generated by ${slicer} 2.1\n; printer_model = Test\n; nozzle_diameter = 0.4,0.6\n; filament_type = PLA,PETG\n; filament_colour = #ffffff,#000000\n; filament used [g] = 2,3\n; layer_height = 0.2\n; first_layer_height = 0.25\n; total_layer_count = 42\n; estimated printing time = 1h 2m\n`)
    expect(metadata.slicer).toBe(slicer === 'Cura_SteamEngine' ? 'Cura' : slicer)
    expect(metadata.tools).toEqual([{ nozzleDiameter: 0.4, filamentType: 'PLA', filamentColour: '#ffffff', filamentGrams: 2 }, { nozzleDiameter: 0.6, filamentType: 'PETG', filamentColour: '#000000', filamentGrams: 3 }])
    expect(metadata).toMatchObject({ printerModel: 'Test', layerHeight: 0.2, firstLayerHeight: 0.25, totalLayers: 42, estimatedTimeSeconds: 3720 })
  })
  it('recognizes Cura flavor and ignores unknown or malformed content', () => {
    expect(parseGcodeMetadataText(';FLAVOR:Marlin').slicer).toBe('Cura')
    expect(parseGcodeMetadataText('G1 X1\n; broken = \n' + 'x'.repeat(600000))).toEqual({})
    expect(PrintFileMetadata.safeParse(parseGcodeMetadataText('; layer_height = -1\n; thumbnail begin 2x2 10\n; !!!')).success).toBe(true)
  })
  it('retains the largest valid PNG or JPEG and skips QOI and oversized data', () => {
    const png = btoa('\x89PNG\r\n\x1a\nabc')
    const jpg = btoa('\xff\xd8\xff' + 'x'.repeat(20))
    const block = (type: string, data: string) => `; thumbnail${type} begin 10x10 ${data.length}\n; ${data}\n; thumbnail${type} end\n`
    const result = parseGcodeMetadataText(block('', png) + block('_JPG', jpg) + block('_QOI', btoa('qoif' + 'x'.repeat(100))))
    expect(result.thumbnail).toEqual({ mimeType: 'image/jpeg', data: jpg })
    expect(parseGcodeMetadataText(block('', btoa('\x89PNG\r\n\x1a\n' + 'x'.repeat(262145)))).thumbnail).toBeUndefined()
  })
  it('reads less than 8 MiB from a 512 MiB sparse file', async () => {
    const dir = await mkdtemp(join(tmpdir(), 'gcode-374-'))
    const file = await open(join(dir, 'sparse.gcode'), 'w+')
    try {
      await file.truncate(512 * 1024 * 1024)
      await file.write('; generated by OrcaSlicer 2.0\n', 0)
      await file.write('\n; total_layer_count = 99\n', 512 * 1024 * 1024 - 25)
      let readBytes = 0
      const result = await parseGcodeMetadata({ size: 512 * 1024 * 1024, async read(offset, length) {
        const buffer = Buffer.alloc(length)
        const { bytesRead } = await file.read(buffer, 0, length, offset)
        readBytes += bytesRead
        return buffer.subarray(0, bytesRead)
      } })
      expect(readBytes).toBeLessThan(8 * 1024 * 1024)
      expect(result).toMatchObject({ slicer: 'OrcaSlicer', totalLayers: 99 })
    } finally { await file.close(); await rm(dir, { recursive: true, force: true }) }
  })
})
